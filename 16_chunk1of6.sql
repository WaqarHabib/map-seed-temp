## Anatomy of an Australian product recall

A well-run voluntary recall in Australia follows this pattern:

1. **Decision**: the supplier identifies a safety issue (through incident reports, testing or complaints) and decides a recall is warranted, notifying the ACCC.
2. **Scope**: affected models, batch numbers and date ranges are defined precisely; vague scope undermines the recall.
3. **Notice**: the recall notice is published on Product Safety Australia and through the supplier's channels, with clear product identification, hazard description, what consumers should do, and contact details.
4. **Remedy**: refund, repair or replacement is offered; the remedy must be genuinely accessible (prepaid return shipping, local drop-off points).
5. **Outreach**: suppliers use purchase records, loyalty data and advertising to reach affected consumers.
6. **Effectiveness reporting**: the supplier reports return rates and corrective outcomes to the ACCC.

The ACCC assesses whether the recall is effective; poor return rates or consumer complaints can trigger escalation, including compulsory recall orders and public warnings.

## The 2-day mandatory report in detail

Sections 131-132 deserve close attention because the duty is unusually strict:

- **Who reports**: any supplier in the chain (manufacturer, importer, distributor, retailer) that becomes aware of the association. Multiple suppliers may each have a duty.
- **What triggers it**: becoming aware that the goods were associated with a death, serious injury or serious illness. "Associated" is deliberately broad; causation need not be established.
- **Timeline**: within 2 days of becoming aware. Weekends and holidays do not pause the clock in practice, so procedures must work every day.
- **Content**: the prescribed information about the goods, the incident and the supplier's response.
- **Consequence of failure**: failure to report is itself a contravention, attracting penalties independently of the underlying safety issue.

Businesses should run tabletop exercises: simulate a serious incident report arriving on a Friday evening and verify the 2-day notification can actually be made.

