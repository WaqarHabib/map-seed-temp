## Mandatory standards: how they work in practice

A mandatory standard typically does several things at once:

- **References a voluntary standard**: most mandatory standards adopt an Australian (or joint Australian/New Zealand) standard, sometimes with variations. Compliance means meeting the referenced standard as varied.
- **Sets labelling and warnings**: age gradings, warnings and instructions are commonly prescribed.
- **Defines testing**: the standard specifies test methods; businesses must test to those methods, not to approximations.

Practical compliance follows a pattern: identify the standard, obtain the current referenced version (standards are updated, and the mandatory instrument specifies which edition applies), test production-representative samples through a competent laboratory, and re-test on design or material changes. Because standards evolve, subscribe to update notices from Standards Australia and the ACCC for your categories.

**Consumer guarantees in practice.** The guarantee regime deserves emphasis because it generates more disputes than the safety provisions. Key points:

- Guarantees apply to goods under a threshold value (currently $100,000) bought for personal, domestic or household use, and cannot be excluded by contract.
- For a **major failure** (including safety defects), the consumer chooses between refund, replacement or compensation; the supplier cannot insist on repair.
- Businesses must not mislead consumers about guarantee rights ("no refunds" signs, for example, are unlawful where guarantees apply).
- Manufacturers as well as suppliers owe guarantees, so importers and brand owners face direct consumer claims.

