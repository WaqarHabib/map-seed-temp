4. The manufacturer draws up the EU Declaration of Conformity, affixes the CE marking and keeps technical documentation for 10 years.

## Safety requirements

Alongside sustainability, the regulation sets safety requirements for stationary battery energy storage systems, LMT and EV batteries: they must be designed and manufactured to minimise safety risks, with protection against overheating, thermal runaway, mechanical damage and short circuits. Safety testing follows harmonised standards and the manufacturer's risk assessment. For businesses integrating batteries into products, this means battery safety documentation must be available as part of the host product's own conformity file, and any battery management system behaviour relevant to safety should be covered by the technical documentation.

## Extended producer responsibility and waste batteries

Producers of batteries must register in **each member state** where they first make batteries available (Article 55), including distance sellers, who must appoint an authorised representative for EPR where they have no establishment in the member state. Producers must finance and organise the separate collection, treatment and recycling of waste batteries, meeting binding collection targets (63% of portable batteries by end 2027, 73% by end 2030; LMT targets of 51% by 2028 and 61% by 2031). Treatment must use best available techniques and meet minimum recycling efficiencies and material recovery levels set in the regulation.

## Enforcement and penalties

- Member states must lay down penalties that are effective, proportionate and dissuasive.
- Market surveillance authorities can order corrective measures, withdrawal and recall of non-compliant batteries.
- EPR enforcement is national: selling batteries in a member state without producer registration can lead to sales bans and fines.
- Due diligence verification by notified bodies adds a third-party check on supply chain claims.

## Staying current

1. Track delegated acts on carbon footprint methodology, performance classes and maximum thresholds; these determine the real stringency of the sustainability duties.
2. Prepare battery passport data systems well before February 2027; the data collection burden is significant.
3. Review product design against the 2027 removability rules now, since redesign cycles are long.
4. Confirm EPR registration in every member state of sale, including via authorised representatives for distance sales.
5. Treat the regulation as a data regulation as much as a product regulation: carbon, recycled content, due diligence and passport duties all depend on supply chain data you should start collecting now.

## Frequently asked questions

**Does the regulation apply to the battery inside my product, or only to standalone batteries?**
Both. Batteries incorporated into appliances, equipment or vehicles must comply, and the removability rules directly constrain how you design the host product.

**I sell battery-containing products online to EU customers from outside the EU. Do I need EPR registration?**
Yes. Distance sellers are treated as producers and must register in each member state where they make batteries available, appointing an authorised representative for EPR purposes where they have no local establishment.

**What is the battery passport, in practical terms?**
An electronic record for each LMT, large industrial or EV battery, accessible by scanning the QR code on the battery from 18 February 2027. It carries data on characteristics, carbon footprint, materials and supply chain. Businesses need data systems capable of generating and maintaining it.

**Do I need a notified body?**
It depends on the requirement. Sustainability and safety requirements use Modules A, B+C or H1; due diligence policies must be verified by a notified body. Check Annex VIII against each applicable requirement.

**Are there substance bans?**
The regulation restricts mercury, cadmium and lead content. Broader chemical restrictions continue to apply through REACH and product-specific law.

