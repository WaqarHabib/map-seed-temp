## Scope and who must comply

The ACL's product safety provisions apply to **consumer goods**: goods intended or likely to be used for personal, domestic or household purposes. Suppliers include manufacturers, importers, distributors and retailers. Importers are in the front line for overseas-made goods, and online sellers (including overseas sellers supplying Australian consumers) are within scope.

The framework has several interlocking parts:

- **Mandatory safety standards**: the Commonwealth minister can impose mandatory standards prescribing requirements for particular goods (around 40 exist, covering products such as toys, children's nightwear, cots, prams, exercise cycles, portable pools, gas appliances and more). Supplying goods that do not comply with an applicable mandatory standard is prohibited.
- **Interim and permanent bans**: goods can be banned where they are or may become unsafe. Interim bans (up to 18 months, extendable) address emerging risks quickly; permanent bans follow full assessment.
- **Recalls**: suppliers can conduct voluntary recalls, and the minister can order compulsory recalls. Recall notices follow prescribed requirements and are published on the Product Safety Australia website.
- **Consumer guarantees**: goods must be of acceptable quality, fit for purpose and safe, with remedies (repair, replacement, refund) for major failures. These guarantees apply regardless of any warranty the business offers.

## Key obligations

**Comply with mandatory standards.** Before supplying goods, check whether a mandatory standard applies to the product type. Standards prescribe design, construction, performance, testing and labelling requirements. Compliance must be verified through testing to the referenced standards; supplier assertions alone are not sufficient.

**Mandatory incident reporting (sections 131-132).** If you are a supplier (manufacturer, importer, distributor or retailer) and you become aware that a consumer good you supplied was associated with the death or serious injury or illness of any person, you must notify the ACCC **within 2 days**. This is one of the strictest reporting duties in the world: the trigger is association, not proven causation, and the clock is very short. Businesses need standing procedures to identify and escalate such events.

**Conduct recalls properly.** Where goods are unsafe, suppliers should conduct voluntary recalls in accordance with ACCC guidance: notify the ACCC, publish the recall notice, identify affected batches, offer an appropriate remedy and report on recall effectiveness. Compulsory recalls can be ordered where voluntary action is inadequate.

**Honour consumer guarantees.** The guarantee of acceptable quality includes safety: goods must be safe for their normal use. Consumers are entitled to remedies for major failures, and businesses cannot contract out of the guarantees or mislead consumers about their rights.

**Information standards.** The minister can also set information standards requiring prescribed information (labelling, warnings) for goods, which operate alongside safety standards.

