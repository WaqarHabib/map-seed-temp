## Scope and who must comply

The CCPSA applies to **consumer products**: products (including components, parts and accessories) that may reasonably be expected to be obtained by an individual for non-commercial purposes, including domestic, recreational and sports purposes. It covers manufacturers, importers, advertisers and sellers, with importers carrying front-line responsibility for products made abroad.

Excluded products include those already regulated elsewhere (tobacco, food, drugs, medical devices, cosmetics under the Food and Drugs Act, motor vehicles, firearms and others listed in Schedule 1). Cosmetics have their own regime: the Food and Drugs Act prohibits the sale of cosmetics that may cause injury, and the Cosmetic Regulations require **notification to Health Canada within 10 days after first sale** in Canada, with ingredient disclosure under the Cosmetic Ingredient Hotlist.

In addition to the general prohibition, the CCPSA is supplemented by product-specific regulations (for example, cribs, children's sleepwear flammability, corded window coverings, surface coating materials) that businesses must check for their product category.

## Key obligations

**General prohibition (section 7).** No person shall manufacture, import, advertise or sell a consumer product that is a danger to human health or safety. This is the Act's cornerstone: unlike regimes built on pre-market certification, Canada relies on a broad prohibition backed by strong post-market powers.

**Incident reporting (section 14).** A person who manufactures, imports or sells a consumer product for commercial purposes must report to Health Canada when they become aware of an **incident** (a death, serious adverse health effect, or a product defect that could reasonably be expected to result in death or serious adverse effects):

- **Within 2 days** of becoming aware: provide Health Canada with the prescribed information about the incident.
- **Within 10 days**: provide a written report with the prescribed information, including the product details and any corrective measures taken or planned.

The tight timelines mean businesses need standing procedures for identifying, escalating and reporting incidents.

**Recordkeeping.** Commercial manufacturers, importers and sellers must maintain documents identifying the product's name, the supplier and customer, and the period of supply, and must provide them to Health Canada on request. Traceability is essential for recalls.

**Recalls and orders.** Health Canada can order a recall where a product is a danger to health or safety (section 31), and can order a person to take corrective measures. Refusal or failure to comply is an offence. Voluntary recalls are conducted in cooperation with Health Canada and published in the Recalls and Safety Alerts database.

**Cosmetics notification.** Manufacturers and importers must notify Health Canada of each cosmetic product within 10 days after first sale in Canada, providing formulation information. Products must comply with the Cosmetic Ingredient Hotlist (prohibited and restricted ingredients).

