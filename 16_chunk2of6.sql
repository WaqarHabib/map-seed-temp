**Short answer:** Regulation (EU) 2023/1230 replaces the Machinery Directive (2006/42/EC) with a directly applicable regulation setting essential health and safety requirements for machinery placed on the EU market. It modernises the rules for digital technologies (AI, connected machinery, cybersecurity), allows digital instructions, and clarifies duties when machinery is substantially modified. It applies from 20 January 2027 and affects machinery manufacturers, importers, distributors and anyone modifying machinery in ways that affect safety.

