## Frequently asked questions

**When does the Machinery Regulation start applying?**
20 January 2027. It repeals the Machinery Directive from that date. Certain provisions on notified bodies (Article 6) apply earlier. Machinery placed on the market before that date under the directive remains valid.

**Can I provide instructions only as a PDF or on a website?**
Digital instructions are permitted, but the purchaser must be able to access them easily and can request a paper copy free of charge at the time of purchase. Safety information that must accompany the machinery has specific format expectations, so check the regulation's conditions.

**What is a substantial modification?**
A modification (physical or digital) not foreseen by the manufacturer that creates a new hazard or increases an existing risk. The person carrying it out must perform a new conformity assessment and is treated as the manufacturer, with all associated duties.

**Do I need a notified body?**
For Annex I Part A machinery, yes. For Part B machinery, only where harmonised standards do not fully cover the applicable requirements. Other machinery can use internal production control (Module A).

**What about partly completed machinery?**
It is not CE-marked. The manufacturer provides a declaration of incorporation and assembly instructions, and the final machinery assembler carries out the full conformity assessment.

