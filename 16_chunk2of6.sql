## Scope and who must comply

The regulation covers **machinery** (assemblies of linked parts with at least one moving part, joined for a specific application), **partly completed machinery**, interchangeable equipment, safety components, lifting accessories, chains, ropes and webbing, and removable mechanical transmission devices. It applies to manufacturers, authorised representatives, importers, distributors and fulfilment service providers, with the standard NLF allocation of duties.

Two scope concepts are particularly important:

- **Substantial modification**: a modification to machinery, by physical or digital means, that is not foreseen by the manufacturer and that creates a new hazard or increases an existing risk, requiring new conformity assessment. Anyone carrying out a substantial modification is treated as the manufacturer of the modified machinery.
- **High-risk machinery**: Annex I lists categories of machinery subject to stricter conformity assessment. Part A lists machinery for which third-party assessment is always required; Part B lists machinery where the manufacturer may choose between third-party assessment and internal checks with harmonised standards.

The regulation excludes certain products covered by more specific EU law (such as medical devices, and machinery for military or police purposes) and means of transport already regulated elsewhere.

## Key obligations

**Essential health and safety requirements (Annex III).** Machinery must be designed and constructed to be fit for purpose and safe, addressing mechanical hazards, control systems, moving parts, vibration, noise, radiation, emissions, maintenance access and ergonomics. New or strengthened provisions address:

- **Connected machinery and cybersecurity**: protection against corruption of safety functions through cyber threats, with security-by-design expectations for machinery with digital elements.
- **AI and autonomous behaviour**: requirements on the safety of machinery with evolving or autonomous behaviour, including transparency and human oversight concepts.
- **Collaborative robots**: updated thinking on human-robot collaboration risks.

**Risk assessment.** The manufacturer must carry out a risk assessment to determine which essential requirements apply and what protective measures are needed, following the iterative process in Annex III (eliminate or reduce risks by design, add protective measures, inform users of residual risks).

**Instructions.** Instructions for use may be provided in **digital format** (a major modernisation), provided the customer can access them easily; a paper copy must be provided free of charge on request at the time of purchase. Safety-critical information must still be available in paper where the regulation requires.

**Traceability and marking.** Machinery must bear the manufacturer's name, address, designation, serial number, year of construction and the CE marking, with importers adding their details where applicable.

## Conformity process

1. **Risk assessment** against Annex III essential health and safety requirements.
2. **Harmonised standards**: applying harmonised standards published in the Official Journal gives presumption of conformity. The existing stock of harmonised standards under the Machinery Directive is being transitioned.
3. **Conformity assessment (Annexes)**:
   - For non-Annex I machinery, or Annex I Part B machinery manufactured in accordance with harmonised standards covering all relevant requirements: internal production control (Module A).
   - For Annex I Part A machinery, and Part B machinery not fully covered by harmonised standards: EU-type examination (Module B) plus internal production control, or full quality assurance (Module H).
4. **EU Declaration of Conformity** and **CE marking** before placing on the market.
5. **Technical documentation** (Annex IV) kept for 10 years.

Partly completed machinery follows a lighter regime: a declaration of incorporation and assembly instructions rather than full CE marking, since it cannot function independently.

## Notified bodies and their role

Notified bodies are conformity assessment bodies designated by member states and notified to the Commission to carry out third-party assessment under the regulation. Their involvement is mandatory for Annex I Part A machinery and for Part B machinery where harmonised standards do not fully cover the applicable essential requirements.

Working with a notified body typically follows this pattern:

1. **Application**: the manufacturer submits the technical file, risk assessment and a representative specimen or design dossier.
2. **EU-type examination (Module B)**: the notified body examines the technical design and tests the specimen against the essential requirements.
3. **Production surveillance**: depending on the module, the notified body audits the quality system or tests production samples to ensure continued conformity to the approved type.
4. **Certificates and numbering**: the notified body's identification number follows the CE marking where it was involved in the production-control phase.

Manufacturers should select a notified body designated for the relevant machinery category and confirm its notification scope in the Commission's NANDO database before contracting. Lead times for EU-type examination can be significant, so high-risk machinery projects should engage a notified body during the design phase rather than after production.

## Documentation and labelling

- Technical file per Annex IV: design documentation, risk assessment, test reports, list of standards applied, and the instructions.
- EU Declaration of Conformity (or declaration of incorporation for partly completed machinery).
- CE marking on the machinery (not on partly completed machinery).
- Marking particulars: business name and address, machinery designation, serial/batch identification, year of construction.
- Instructions in the official language(s) of the member state where the machinery is placed on the market (digital permitted with conditions).

## Enforcement and penalties

- National market surveillance authorities enforce under Regulation (EU) 2019/1020, with powers to require corrective action, order withdrawal or recall, and restrict dangerous machinery.
- Serious risks are notified through Safety Gate.
- Member states must lay down penalties that are effective, proportionate and dissuasive; national regimes include fines and criminal sanctions.
- The substantial-modification rule is an enforcement focus: retrofitters, integrators and end users who modify machinery must recognise when they become the manufacturer.

