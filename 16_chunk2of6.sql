**Short answer:** The Ecodesign for Sustainable Products Regulation (EU) 2024/1781 is the EU's framework for making products more durable, repairable, recyclable and resource-efficient. In force since 18 July 2024, it empowers the Commission to set product-specific ecodesign requirements through delegated acts, introduces the Digital Product Passport for tracing product sustainability data, and bans the destruction of unsold textiles and footwear by large enterprises. It affects manufacturers, importers and distributors of physical goods sold in the EU across almost all product categories.

