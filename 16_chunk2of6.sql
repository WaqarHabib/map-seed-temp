## Staying current

1. Track the Commission's working plans and the register of delegated acts: your duties begin when a delegated act for your product group applies, and transition periods are limited.
2. Start building product data systems now; the DPP requires structured sustainability data across the supply chain, which cannot be assembled retrospectively at low cost.
3. Review design practices against the likely requirement families (durability, reparability, recycled content, substances of concern) so future delegated acts require adjustment rather than redesign.
4. If you are a large enterprise in textiles or footwear, address the unsold-products destruction ban and disclosure duties as a priority.

## Frequently asked questions

**Does the ESPR apply to my product today?**
The framework applies, but concrete ecodesign duties apply only once a delegated act covers your product group. Check the Commission's working plans and adopted delegated acts for your category rather than assuming you are unaffected.

**What is the Digital Product Passport?**
An electronic record linked to each product via a data carrier (such as a QR code), carrying sustainability information: materials, substances of concern, repairability, recycled content, carbon footprint and compliance data. Access is tiered between the public, supply chain actors and authorities.

**How is this different from the old Ecodesign Directive?**
The old directive covered only energy-related products (plus implementing measures). The ESPR extends ecodesign to almost all physical goods and adds the DPP, substances-of-concern tracking and the unsold-products destruction ban.

**I am an importer, not a manufacturer. What must I do?**
Importers must verify the manufacturer has carried out the conformity assessment, ensure the DPP and data carrier are present, keep the EU Declaration of Conformity, and cooperate with authorities. If you place products on the market under your own brand, you assume manufacturer duties.

**When does the ban on destroying unsold products apply?**
The regulation prohibits destruction of unsold textiles and footwear by large enterprises, with derogations set by delegated act. Large enterprises must also disclose information on destroyed unsold consumer products. Check the current delegated acts for exact scope and dates.

