| ICSMS (Information and Communication System for Market Surveillance) | Authorities share inspection results, test reports and enforcement actions; the public interface allows searching product investigations |
| Safety Gate (formerly RAPEX) | Rapid alerts on dangerous non-food products, notified by national authorities |
| Safety Business Gateway | Businesses notify authorities of risks and accidents |
| Union Product Compliance Network | Coordinates joint actions, shared testing and best practice among authorities |

Businesses can use the public ICSMS interface to see which product categories authorities are actively investigating, which is a useful input to compliance risk planning.

## Enforcement and penalties

- Authorities follow an escalation ladder: request for documentation, corrective action within a set deadline, then withdrawal, recall, import suspension or prohibition.
- Products presenting a **serious risk** trigger rapid measures, EU-wide alerts and coordinated action.
- Article 41 requires member states to lay down penalties that are effective, proportionate and dissuasive; the actual fines and criminal sanctions are set nationally and vary by member state.
- Customs can refuse or suspend release for free circulation, which in practice stops non-compliant shipments at the border before they reach customers.

## Placing on the market: the trigger point

The regulation's duties attach to "placing on the market" (the first making available of a product on the EU market) and "making available" (any subsequent supply). This distinction matters because the Article 4 responsible operator must exist from the moment of first placing, and border controls apply at the point products are presented for release for free circulation. Products already on the market before 16 July 2021 were subject to transitional arrangements, but any product placed on the market today must have its compliance chain complete before it reaches the customer.

Fulfilment service providers deserve particular attention. A warehouse that merely stores goods is not automatically an Article 4 operator; it becomes one only where no manufacturer, importer or authorised representative is established in the EU and the provider accepts the mandated tasks. Businesses using third-party logistics in the EU should confirm in writing which entity performs the Article 4 role, because authorities will ask for a named contact with real access to the technical documentation.

## Practical compliance checklist

1. Map every regulated product to its EU-established responsible operator and record the arrangement.
2. Ensure the operator's name and contact details appear on the product, packaging, parcel or accompanying document as required.
3. Keep the EU Declaration of Conformity and technical documentation retrievable within days, not weeks.
4. Build a border-incident procedure: who responds if customs suspends release, and what evidence is sent to the market surveillance authority.
5. For online sales, maintain product listings that match the certified product (photos, model numbers, warnings) and a rapid takedown-response process.
6. Review ICSMS and Safety Gate periodically for your product category to anticipate enforcement focus.

## Staying current

1. Confirm that every regulated product you place on the EU market has a valid Article 4 operator established in the EU, and that the arrangement is documented (a fulfilment warehouse alone does not qualify unless it accepts the mandated tasks).
2. Keep the EU Declaration of Conformity and technical documentation retrievable at short notice; authorities work to tight deadlines, especially at the border.
3. Watch the Union Product Compliance Network's joint actions and ICSMS entries for your product category to anticipate enforcement focus.
4. If you sell online, maintain a takedown-response procedure so you can act quickly if an authority orders removal of a listing.

## Frequently asked questions

**I am a non-EU manufacturer selling through an EU distributor. Who is the Article 4 operator?**
Your EU importer or distributor can serve as the Article 4 operator, provided they accept the tasks. If you use a fulfilment service provider in the EU and have no importer or authorised representative there, the fulfilment service provider can be designated. The key point is that someone established in the EU must be identifiable and able to perform the Article 4(3) tasks.

**Does Article 4 apply to all products?**
It applies to products subject to the harmonisation legislation listed in Annex I of the regulation, which covers most CE-marked categories. For non-harmonised consumer products, the GPSR's Article 16 creates a parallel requirement.

**Can authorities really order an online marketplace to remove my listing?**
Yes. Article 14(4)(k) gives market surveillance authorities the power to require the removal of content from an online interface or the restriction of access to it where products present a serious risk and other measures are insufficient.

**What happens at the border if my shipment is stopped?**
Customs suspends release and notifies the market surveillance authority, which has a short deadline (generally three working days, extendable) to decide. Outcomes range from release, to release conditional on corrective action, to prohibition of placing on the market.

**Where can I see what authorities are investigating?**
The public interface of ICSMS publishes information on product investigations. Safety Gate publishes rapid alerts on dangerous products.

