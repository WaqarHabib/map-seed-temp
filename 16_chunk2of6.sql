## Staying current

1. Track European standards cited in the Official Journal for your product category; they are the fastest route to presumption of conformity.
2. Monitor the Safety Gate portal for alerts in your product category to calibrate your safety assessment.
3. If you sell at a distance into the EU from outside the EU, confirm your Article 16 responsible-person arrangement is documented and that the person can actually perform the required tasks.
4. Keep accident-reporting procedures ready: the "without undue delay" standard rewards businesses that have internal escalation paths prepared in advance.

## Frequently asked questions

**My product already bears the CE marking under another EU law. Does the GPSR still apply?**
Where sector-specific EU harmonisation legislation covers the safety aspects, that legislation takes precedence. The GPSR applies to aspects of risk not covered by the sector legislation, so it can apply in parallel. Check the scope provisions of both acts.

**I am a non-EU seller shipping directly to EU consumers. What must I do?**
You need an economic operator established in the EU who is responsible for the product-safety tasks (Article 16). This can be an importer, an authorised representative or a fulfilment service provider meeting the conditions. Without this arrangement the product may not be placed on the market.

**Does the GPSR require third-party testing or certification?**
No. Unlike NLF-based product legislation, the GPSR has no conformity assessment modules and no notified bodies. Safety is demonstrated through the manufacturer's own assessment, documentation and use of applicable standards.

**How quickly must accidents be reported?**
Manufacturers must notify the competent authorities without undue delay after learning of an accident, via the Safety Business Gateway. Importers and distributors must pass information up the chain without undue delay. Businesses should define internal timelines in advance rather than improvising after an incident.

**What changed for online marketplaces compared with the old directive?**
The GPSR gives marketplaces explicit, directly applicable duties: a single point of contact, Safety Gate registration, notice-and-action procedures, cooperation with authorities, and trader traceability. These go well beyond the old directive's framework.

**Where is the official text?**
On EUR-Lex as Regulation (EU) 2023/988 (CELEX 32023R0988). The Commission's product safety pages and the Safety Gate portal provide operational guidance.

