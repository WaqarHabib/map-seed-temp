## Scope and who must comply

The regulation applies to products subject to the EU harmonisation legislation listed in its Annex I, which covers the great majority of CE-marked product categories (machinery, radio equipment, toys, electrical equipment, medical devices, construction products and many more). It does not set product requirements itself; it sets the rules for checking compliance and taking action against non-compliance.

Its central innovation is Article 4: for products subject to the listed legislation, there must be an **economic operator established in the EU** who is responsible for defined compliance tasks. That operator can be:

- the manufacturer established in the EU,
- the importer (where the manufacturer is outside the EU),
- an authorised representative with a written mandate covering the tasks, or
- a fulfilment service provider established in the EU (where no manufacturer, importer or authorised representative is established in the EU).

This closed the long-standing gap of products shipped directly to EU consumers by non-EU sellers with no one in the EU answerable for compliance. The GPSR later extended the same concept to non-harmonised consumer products.

## Key obligations

**The EU responsible operator (Article 4).** The designated operator must:

1. Verify that the EU Declaration of Conformity and the technical documentation have been drawn up and keep them available to authorities.
2. Provide authorities with all information and documentation necessary to demonstrate conformity, on a reasoned request.
3. Cooperate with market surveillance authorities on any action to eliminate risks, including corrective measures.
4. Inform authorities where the operator has reason to believe a product presents a risk.
5. Ensure the product can be identified and that the manufacturer's (and importer's) traceability details are available.

The operator's name and contact details must be indicated on the product, packaging, parcel or accompanying document.

**Cooperation duties.** Economic operators must cooperate with market surveillance authorities, provide documentation within the deadlines set, and take corrective action when required. Online sellers and marketplaces must cooperate on the removal of non-compliant listings.

**Border controls.** Articles 25 to 28 organise controls on products entering the EU market. Customs authorities may suspend the release of products where there are grounds to suspect non-compliance or risk, and must notify market surveillance authorities, who decide within a short deadline whether to allow release, require corrective action or prohibit placing on the market.

## Powers of market surveillance authorities

Article 14 gives authorities a minimum set of harmonised powers, including:

- requiring economic operators to provide documentation and information;
- carrying out on-site inspections and entering premises;
- taking product samples, including through **mystery shopping** (purchases made under a cover identity, including online);
- requiring corrective action, withdrawal or recall;
- ordering the removal of content or the restriction of access to an online interface where products present a serious risk ("take-down" powers for online listings);
- imposing penalties or applying to courts for penalties.

Authorities must act in a proportionate manner and target their controls using risk-based national market surveillance strategies. Serious risks are notified EU-wide through the Safety Gate system, and authorities cooperate through the **Union Product Compliance Network** established by Article 29.

