## Scope and who must comply

The ESPR is a **framework regulation**: it does not itself set ecodesign requirements for specific products. Instead, it establishes the machinery (empowerments, procedures, the Ecodesign Forum, working plans) through which the Commission adopts **delegated acts** setting ecodesign requirements product group by product group. It covers almost all physical goods placed on the market or put into service in the EU, including components and intermediate products, with only narrow exclusions (such as food, feed and medicinal products).

Because it is a framework, a business's concrete duties depend on whether a delegated act covers its product group. The Commission works from multiannual **working plans** prioritising product groups with high environmental impact and improvement potential (textiles, furniture, iron and steel, aluminium, tyres, paints, lubricants, chemicals and energy-related products have been identified as early priorities). Until a delegated act applies to your product, the ESPR's direct duties are limited, but the trajectory is clear: ecodesign requirements will progressively cover most manufactured goods.

Economic operators carry the standard NLF-style roles (manufacturer, authorised representative, importer, distributor, fulfilment service provider), and the regulation also addresses online marketplaces and introduces obligations around the destruction of unsold consumer products.

## Key obligations

**Ecodesign requirements (via delegated acts).** Delegated acts may set requirements on:

- **Durability and reliability**: minimum lifetimes, resistance to stress.
- **Reusability, upgradability and reparability**: availability of spare parts, repair information, design for disassembly.
- **Maintenance and refurbishment**.
- **Substances of concern**: presence must be tracked and disclosed; the regulation foresees restrictions building on REACH and RoHS logic.
- **Energy and resource efficiency**: energy use, water use, material efficiency.
- **Recycled content**: minimum levels of recycled material.
- **Remanufacturing and recycling**: design enabling high-quality recycling.
- **Carbon and environmental footprints**: declaration and, in time, maximum thresholds.
- **Expected generation of waste**.

Requirements can take the form of performance thresholds (products must meet a level) or information requirements (products must disclose data).

**Digital Product Passport (DPP).** Articles 9 to 14 require regulated products to carry a DPP: an electronic record accessible via a data carrier (such as a QR code) on the product, containing information on the product's sustainability characteristics, substances of concern, repair and recycling information. The DPP must remain available for the product's expected lifetime, respect data access tiers (public, supply chain, authorities), and use decentralised data storage. The battery passport under Regulation (EU) 2023/1542 is the first implementation of this concept.

**Destruction of unsold consumer products.** Article 25 prohibits the destruction of unsold textiles and footwear (with limited derogations set by delegated act), applying to large enterprises. The prohibition extends the logic of waste prevention directly into commercial practice: overproduction can no longer be solved by destroying stock. Disclosure obligations on the destruction of unsold consumer products more broadly require large enterprises to report volumes destroyed and reasons.

**Market surveillance and compliance.** The regulation integrates with the market surveillance framework (Regulation (EU) 2019/1020), and delegated acts specify the conformity assessment procedures (generally NLF modules) for each product group.

## How delegated acts are made: Forum, working plans and SME considerations

Businesses often ask where they can influence or anticipate ESPR requirements. The regulation creates an **Ecodesign Forum**: a balanced expert group of member states, industry (including SMEs and craft industry), trade unions, traders, retailers, importers, environmental and consumer organisations that the Commission must consult when preparing delegated acts. Participation, directly or through trade associations, is the main channel for shaping requirements before they are fixed.

Delegated acts are prepared under multiannual **working plans** that list the product groups to be addressed. Each act is preceded by impact assessment and stakeholder consultation, and includes transitional periods. The regulation also requires the Commission to consider SME impacts specifically: micro-enterprises and SMEs receive tailored support, guidance and, where justified, adapted timelines or simplified procedures. For small businesses, the practical implication is to join the relevant industry association early, because by the time a delegated act is published, the requirements are settled and only the transition timetable can be managed.

## Conformity process

Until a delegated act covers your product, there is no ESPR conformity assessment to perform. Once covered:

1. Identify the delegated act for your product group and its applicable ecodesign requirements and dates.
2. Assess the product against the performance and information requirements, using harmonised standards or common specifications where available.
3. Carry out the conformity assessment procedure specified in the delegated act (drawn from the NLF modules).
4. Draw up the EU Declaration of Conformity and affix the CE marking (ecodesign compliance is integrated into the CE marking logic).
5. Create and maintain the Digital Product Passport with the required data, linked via the data carrier on the product.
6. Keep technical documentation for the period specified (generally 10 years).

## Documentation and labelling

- Technical documentation demonstrating compliance with the delegated act's requirements.
- EU Declaration of Conformity.
- The **Digital Product Passport**: the central information vehicle, containing product identification, sustainability data, substances of concern, repair/recycling information and compliance evidence, with access rights differentiated by actor.
- Data carrier (for example, QR code) on the product, packaging or documentation linking to the DPP.
- Disclosure reports on destruction of unsold consumer products (for large enterprises).

## Enforcement and penalties

- Market surveillance authorities enforce delegated acts under the Regulation (EU) 2019/1020 framework, including product checks, documentation requests and corrective measures.
- Non-compliant products can be withdrawn or recalled; serious risks are notified through Safety Gate.
- Member states must lay down penalties that are effective, proportionate and dissuasive.
- The unsold-products destruction ban is enforceable against large enterprises, with disclosure duties creating an auditable record.

