## Scope and who must comply

The GPSR applies to products placed or made available on the EU market that are intended for consumers or likely to be used by consumers, where no sector-specific EU harmonisation legislation covers the product's safety aspects. It is the default safety regime: if your product is not governed by a specific directive or regulation (toys, machinery, radio equipment, medical devices and similar), the GPSR is almost certainly the applicable law.

The regulation names the following economic operators and gives each tailored duties:

- **Manufacturers**: primary responsibility for the general safety requirement, technical documentation, traceability marking and accident reporting.
- **Authorised representatives**: where appointed by written mandate.
- **Importers**: EU-established businesses placing third-country products on the EU market; they must verify the manufacturer's compliance steps before placing products on the market.
- **Distributors**: must exercise due care and verify traceability and documentation before making products available.
- **Fulfilment service providers**: warehousing, packaging, addressing and dispatching services are brought into scope with defined obligations.
- **Online marketplaces and other distance sellers**: subject to dedicated obligations, including a single point of contact, cooperation with market surveillance, and trader traceability duties.

A pivotal rule in Article 16: a product covered by the GPSR may not be placed on the market unless there is an economic operator established in the EU responsible for product-safety tasks. Non-EU sellers (including dropshippers and marketplace sellers outside the EU) therefore need an EU-based responsible person, such as an importer, authorised representative or fulfilment service provider.

## Key obligations

**The general safety requirement.** Article 5 requires economic operators to place only safe products on the market. Article 6 lists the criteria for assessing safety: product characteristics, presentation and labelling, the categories of consumers at risk (with particular attention to children, older people and persons with disabilities), and cybersecurity features where the product has digital elements.

**Traceability.** Manufacturers must ensure products bear a type, batch or serial number or other element allowing identification, and must indicate their name, registered trade name or trademark and a postal and electronic contact address (Article 9). Importers must add their own name and contact details (Article 11). Economic operators must keep records of their suppliers and customers to ensure traceability through the chain.

**Technical documentation.** Manufacturers must draw up technical documentation containing a general description of the product and the measures taken to ensure its safety, and keep it available to market surveillance authorities. Documentation duties are lighter than under NLF harmonisation legislation but must be sufficient to demonstrate the safety assessment.

**Accident reporting.** Article 20 requires manufacturers who know (or should know) that a product they placed on the market has caused an accident to notify the competent authorities of the member states where the accident occurred, without undue delay, through the Safety Business Gateway. Importers and distributors must inform the manufacturer (or importer) without undue delay when they learn of an accident.

**Online marketplace duties.** Article 22 requires providers of online marketplaces to designate a single point of contact for authorities and consumers, register with the Safety Gate portal, act on notices about dangerous products (notice-and-action), cooperate with market surveillance authorities including on product-safety sweeps, and ensure traceability of traders using their services.

## Conformity process

The GPSR does not use the NLF conformity assessment modules or CE marking. Instead, compliance is demonstrated through:

1. **Safety assessment**: the manufacturer assesses the product against the Article 6 criteria, considering foreseeable use and misuse, vulnerable consumer groups and, for connected products, cybersecurity risks.
2. **Standards**: compliance with European standards whose references are published in the Official Journal gives a presumption of conformity with the general safety requirement. Where no such standards exist, manufacturers use national standards, Commission guidance, industry codes of practice and the state of the art.
3. **Documentation**: drawing up and maintaining the technical documentation described above.
4. **Ongoing monitoring**: manufacturers must investigate complaints, keep a register of complaints and recalls where appropriate, and keep distributors informed of safety issues.

There is no notified body system under the GPSR. The emphasis is on the manufacturer's own safety assessment, supported by standards and documented evidence.

## Documentation and labelling

Required elements on the product, its packaging or accompanying documents:

- Type, batch or serial number (or another identifier) for traceability.
- Manufacturer's name, registered trade name or trademark, plus postal address and electronic address.
- Importer's name, registered trade name or trademark, plus postal address and electronic address, where the importer places the product on the market.
- Instructions and safety information in the language(s) determined by the member state where the product is made available, in clear and comprehensible form.
- Warnings where needed to address residual risks identified in the safety assessment.

Technical documentation must be kept up to date and made available to market surveillance authorities on request. Complaint and recall registers should be maintained where proportionate to the risk.

## Enforcement and penalties

- **Market surveillance**: national authorities can order corrective measures, withdrawals and recalls, and can restrict or ban products presenting a serious risk. Dangerous products are notified EU-wide through the **Safety Gate** rapid alert system (the successor to RAPEX), and businesses notify authorities through the **Safety Business Gateway**.
- **Online enforcement**: authorities can order marketplaces to remove listings for dangerous products and to warn consumers.
- **Penalties**: Article 44 requires member states to lay down penalties that are effective, proportionate and dissuasive. National penalty regimes differ, so businesses should check the implementing rules in each member state where they sell.

