## Scope and who must comply

The regulation covers **all packaging** placed on the market in the EU, regardless of material: sales (primary), grouped (secondary) and transport (tertiary) packaging. It applies to manufacturers, suppliers, importers, distributors, fulfilment service providers and final distributors, with extended producer responsibility falling on **producers** (generally the first placer on the market in a member state, with specific rules for distance sellers and online marketplaces).

Because nearly every physical product is packaged, the PPWR's reach is exceptionally broad: from e-commerce sellers shipping parcels to food and beverage companies, electronics brands and industrial suppliers.

## Key obligations and timeline

**Substance restrictions.** Packaging must comply with restrictions on substances, including limits on heavy metals (the long-standing sum of lead, cadmium, mercury and hexavalent chromium) and new provisions on substances of concern. Packaging in contact with food is subject to PFAS-related provisions. Businesses should verify the current consolidated text for the exact limits and dates.

**Design for recycling (Article 6).** From 12 August 2028, packaging must be designed for material recycling according to design-for-recycling criteria set by delegated act, and from 12 February 2030 (with later dates for certain aspects) it must be recyclable at scale. Packaging that fails the criteria faces modulated EPR fees or market restrictions.

**Recycled content targets (Article 7).** For plastic packaging, minimum recycled content targets apply per unit of packaging:

- From 1 January 2030: 30% for contact-sensitive PET packaging; 10% for other contact-sensitive plastic packaging (except single-use beverage bottles); 30% for single-use plastic beverage bottles; 35% for other plastic packaging.
- From 1 January 2040: targets rise to 50%, 25%, 65% and 65% respectively.

Compliance must be demonstrated with robust chain-of-custody evidence, and the Commission will set calculation and verification rules.

**Extended producer responsibility (Article 45).** Producers must register in each member state where they place packaging on the market and join or operate EPR schemes covering collection, sorting and recycling costs. EPR fees are **eco-modulated**: packaging that is easier to recycle pays lower fees, creating a direct financial incentive for design choices.

**Harmonised labelling.** From 12 August 2028, packaging must carry harmonised labels indicating material composition to facilitate sorting; deposit-bearing packaging carries additional marking. Labels may be provided via QR code or other data carrier. The harmonised approach replaces the current patchwork of national labelling schemes (such as the Triman/Info-tri in France and environmental labelling in Italy), though national schemes apply during the transition.

**Deposit return schemes (DRS).** By 1 January 2029, member states must have DRS for single-use plastic beverage bottles and metal beverage containers up to 3 litres, unless they achieve 90% separate collection by other means in 2026 and 2027. Producers of covered containers must participate in the national DRS, with operational implications for labelling, logistics and fee structures.

**Single-use bans (Article 22).** From 12 February 2030, certain single-use plastic packaging formats are banned, including packaging for unprocessed fresh fruit and vegetables under 1.5 kg, single-use packaging for food and beverages filled at the point of sale in the HORECA sector, and miniature toiletry packaging in accommodation. Businesses should check the full list in Article 22 against their packaging portfolio.

**Waste prevention and reuse.** The regulation sets packaging waste reduction targets and reuse targets for specific sectors (for example, transport packaging and HORECA), pushing businesses toward refill and return systems.

## EPR fees and eco-modulation in practice

Extended producer responsibility under the PPWR is not a flat tax; it is designed as a behavioural instrument:

- **Fee base**: fees are generally calculated per unit of packaging or per kilogram placed on the market, differentiated by material.
- **Eco-modulation**: fees are adjusted (bonuses and penalties) based on recyclability criteria from the design-for-recycling delegated acts. Packaging that meets the highest recyclability class pays the lowest fees; hard-to-recycle packaging pays more. This makes packaging design decisions directly visible in the P&L.
- **Cost coverage**: fees must cover the costs of collection, sorting and recycling infrastructure, including litter clean-up costs for certain single-use items.
- **Reporting**: producers report quantities placed on the market by material and format to their schemes, typically quarterly or annually depending on the member state.

For businesses, the implication is that packaging choices should be modelled with EPR fees included: a slightly more expensive but highly recyclable material can be cheaper overall once modulated fees are accounted for. Procurement and packaging design teams should work from the fee schedules of the schemes in their main markets.

## Reuse systems and sector targets

The regulation pushes beyond recycling into reuse. Economic operators in covered sectors must meet reuse and refill targets, for example in transport and grouped packaging and in the HORECA sector. Practically, this means:

- Assessing which packaging flows can shift to reusable formats (pallets, crates, refillable containers).
- Setting up or joining reuse systems with reverse logistics, washing and tracking.
- Documenting reuse rotations to demonstrate target compliance.

Reuse targets apply progressively, so businesses should map their packaging flows now and identify pilot opportunities before the binding dates arrive.

## Conformity process

1. **Packaging inventory**: catalogue every packaging component placed on the EU market by material, weight and function.
2. **Substance and design screening**: check packaging against substance restrictions and the design-for-recycling criteria.
3. **Recycled content planning**: secure supply chains capable of delivering the 2030 and 2040 recycled content targets with verifiable chain of custody.
4. **EPR registration**: register as a producer in each member state of sale and join the relevant schemes.
5. **Labelling**: implement harmonised labels (material composition, deposit marking) by the applicable dates.
6. **DRS participation**: for beverage containers, join national deposit return schemes.
7. **Documentation**: maintain technical documentation demonstrating compliance with substance, design and recycled content requirements.

## Documentation and labelling

- Technical documentation on packaging composition, substances and design-for-recycling assessment.
- Recycled content evidence with chain-of-custody documentation.
- EPR registration numbers and scheme contracts per member state.
- Harmonised material-composition labels (from 12 August 2028), including via QR code where used.
- Deposit markings for DRS packaging.
- Reuse and waste-prevention records where targets apply.

## Enforcement and penalties

- Market surveillance authorities enforce substance, labelling and design requirements; non-compliant packaging can be ordered withdrawn.
- EPR enforcement is national: placing packaged products on the market without producer registration can lead to sales bans and fines.
- Member states must lay down penalties that are effective, proportionate and dissuasive.
- Eco-modulated fees create continuous financial pressure toward recyclable design, independent of formal enforcement.

## Staying current

1. Work from the consolidated regulation text; delegated acts on design-for-recycling criteria, recycled content calculation and labelling formats will define the practical duties.
2. Map packaging EPR per member state now; the regulation harmonises the framework but registers and schemes remain national.
3. Start recycled-content supply chain work early; food-contact recycled plastics in particular face constrained supply and strict safety requirements.
4. Review single-use packaging formats against the Article 22 ban list and plan phase-outs before 2030.

## Frequently asked questions

**Does the PPWR apply to e-commerce shipping packaging?**
Yes. Transport and e-commerce packaging is fully in scope, including EPR registration, design-for-recycling and labelling duties. Distance sellers are treated as producers in the member state of the customer.

**Is there a single EU packaging registration?**
No. As with WEEE and batteries, producer registration is per member state, with national schemes and registers.

**What happens to existing national packaging labels?**
Harmonised EU labels apply from 12 August 2028. National labelling requirements (such as France's Triman or Italy's environmental labelling) continue to apply during the transition; businesses must follow both until the harmonised system takes over.

**Do the recycled content targets apply to all packaging?**
The binding percentage targets in Article 7 apply to plastic packaging. Other materials are addressed through design-for-recycling criteria and eco-modulated EPR fees.

**Are there exemptions for small businesses?**
The regulation includes certain simplifications for small actors in specific provisions, but EPR and core product requirements generally apply regardless of size. Check the applicable articles for your situation rather than assuming an exemption.

