**Short answer:** REACH is the EU's overarching chemicals regulation, in force since 2007. It requires registration of chemical substances manufactured or imported at one tonne or more per year, restricts hazardous substances (Annex XVII), controls substances of very high concern through authorisation (Annex XIV), and imposes communication duties down the supply chain when articles contain SVHCs above 0.1%. It affects chemical manufacturers and importers directly, and every business placing articles (including consumer products) on the EU market through its restriction and communication duties.

