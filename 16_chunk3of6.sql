## Scope and who must comply

Radio equipment means an electrical or electronic product that intentionally emits and/or receives radio waves for radio communication or radiodetermination, or that must be completed with an accessory (such as an antenna) to do so. In practice this covers mobile phones, tablets, laptops with cellular or Wi-Fi, Bluetooth devices, smart home products, connected toys, drones, radio-controlled equipment and countless IoT devices.

The directive applies to manufacturers, authorised representatives, importers and distributors with the standard NLF duties. Pure receivers (such as broadcast radio receivers) fall within scope, while some equipment is excluded (for example, radio equipment used by radio amateurs in certain conditions, marine equipment covered by the Marine Equipment Directive, and aviation products covered by aviation law).

## Key obligations: the essential requirements

**Article 3(1): health, safety and EMC.** Radio equipment must ensure the protection of health and safety of persons (applying the safety objectives of the Low Voltage Directive, but with **no lower voltage limit**, so battery-powered devices are fully covered) and an adequate level of electromagnetic compatibility.

**Article 3(2): radio spectrum.** Equipment must use the spectrum effectively and efficiently to avoid harmful interference. In practice this is demonstrated through harmonised standards (the EN 300 series from ETSI) covering transmitter and receiver performance in the relevant frequency bands.

**Article 3(3): delegated requirements.** The Commission may activate additional essential requirements by delegated act. The significant activations are:

- **Cybersecurity, privacy and fraud prevention**: Delegated Regulation (EU) 2022/30 activates Article 3(3)(d), (e) and (f) for internet-connected radio equipment, requiring safeguards for network protection, personal data and privacy, and protection against fraud. These apply from **1 August 2025** and are among the most consequential recent changes in EU product law for connected devices.
- **Common charger**: Directive (EU) 2022/2380 amended the RED to require a **USB-C receptacle and USB Power Delivery** charging capability for listed categories (mobile phones, tablets, cameras, headphones, portable speakers, handheld consoles and others) from **28 December 2024**, and for laptops from **28 April 2026**, alongside unbundling and labelling rules on charging capabilities.
- Other Article 3(3) activations cover emergency caller location, accessibility for users with disabilities and interoperability in specific cases.

**Registration.** Article 5 foresees a registration system for types of radio equipment with low levels of compliance, operated through a central system; businesses should check whether their equipment type is affected once the system is operational.

## Spectrum use, power limits and national restrictions

Article 3(2) compliance is not only about passing a lab test; it is about the equipment behaving correctly in the actual radio environment. Key practical points:

- **Harmonised standards by band**: ETSI standards (the EN 300 series and related) define transmitter power limits, spurious emissions, receiver blocking and adaptivity requirements for each frequency band and technology. Using the wrong version, or a standard for the wrong band, is a common cause of non-compliance findings.
- **National restrictions on putting into service**: member states may restrict the putting into service of radio equipment where there are spectrum management reasons (for example, bands not harmonised nationally). Where such restrictions exist, the packaging must identify the member states concerned, using the prescribed pictogram and text.
- **Software-defined radio**: where radio characteristics are determined by software, the manufacturer must ensure that only compliant software can be loaded, and must assess the implications of user-installable or over-the-air updates on the conformity assessment.
- **Combined equipment**: products combining radio modules with other functions (for example, a machine with an embedded cellular modem) must satisfy the RED for the radio aspects alongside the other applicable legislation for the host product. Pre-certified radio modules simplify but do not eliminate the host manufacturer's assessment duties: integration, antennas, power supply and enclosure effects must still be evaluated.

## Conformity process

The manufacturer chooses among the Annexes:

| Annex | Procedure | When used |
|---|---|---|
| Annex II | Internal production control (Module A) | Where harmonised standards for all essential requirements have been fully applied |
| Annex III | EU-type examination (Module B) + conformity to type (Module C) | Where harmonised standards are partly applied or absent |
| Annex IV | Full quality assurance (Module H) | Manufacturer operates an approved quality system covering design and production |

In practice, most radio products use Annex II with the full set of harmonised standards (radio/EMC/safety), while products using new radio technologies or lacking harmonised standards need a notified body under Annex III. Software/firmware changes that affect radio parameters can require re-assessment, since the "product" assessed includes its radio behaviour.

Importers must verify the conformity assessment, CE marking, traceability and documentation before placing equipment on the market. Distributors must exercise due care.

## Documentation and labelling

- **EU Declaration of Conformity** (a simplified version may accompany the product with the full text available online).
- **Technical documentation** kept for 10 years, including design information, test reports and the list of harmonised standards applied.
- **CE marking** affixed to the equipment or its data plate (and packaging where size requires), followed by the notified body number where Annex III or IV involved one.
- **Traceability**: type, batch or serial number; manufacturer's name, trade mark and contact address; importer's details where applicable.
- **Information**: instructions and safety information in the language(s) of the member state of sale; for the common-charger categories, labelling on charging capabilities and whether a charger is included.
- **Geographical information**: where equipment is subject to restrictions on putting into service in certain member states (spectrum restrictions), the packaging must identify those member states.

## Enforcement and penalties

- National market surveillance and spectrum authorities test radio equipment for EMC, spectrum efficiency and safety; non-compliant equipment is regularly notified through Safety Gate.
- Authorities can order withdrawal or recall and restrict the putting into service of equipment that causes harmful interference.
- Penalties are national and must be effective, proportionate and dissuasive.
- The 2025 cybersecurity activation and the common-charger rules are current enforcement priorities, with documentation scrutiny expected to be intense.

## Staying current

1. Track ETSI harmonised standards for your frequency bands and equipment type; presumption of conformity for Article 3(2) depends on current OJ references.
2. For internet-connected equipment, treat the August 2025 cybersecurity requirements as a design input now: network safeguards, data protection and fraud prevention must be demonstrable in the technical file.
3. For charger-relevant categories, verify USB-C and USB PD implementation, unbundling and labelling against Directive (EU) 2022/2380.
4. Manage firmware updates as a compliance event: changes affecting radio characteristics or security functions may require re-assessment.

## Frequently asked questions

**Does the RED apply to Wi-Fi and Bluetooth devices?**
Yes. Any product intentionally emitting or receiving radio waves for communication falls within the definition of radio equipment, including short-range devices such as Wi-Fi, Bluetooth, Zigbee and NFC products.

**Do I always need a notified body?**
No. If you fully apply the harmonised standards covering all applicable essential requirements, you may use internal production control (Annex II, self-declaration). A notified body is needed where standards are partly applied or do not exist for your equipment.

**What are the cybersecurity requirements and when do they apply?**
Delegated Regulation (EU) 2022/30 activates RED Article 3(3)(d), (e) and (f) for internet-connected radio equipment from 1 August 2025, requiring protection against network harm, safeguards for personal data and privacy, and protection against fraud. Harmonised standards supporting these requirements are being developed.

**What is the common charger rule?**
Directive (EU) 2022/2380 requires listed device categories to use USB-C charging receptacles with USB Power Delivery, with harmonised labelling of charging capabilities and rules on unbundling chargers from devices. It applies from 28 December 2024 (laptops from 28 April 2026).

**I only change the firmware, not the hardware. Do I need re-assessment?**
Possibly. If the change affects radio parameters, EMC behaviour or security functions covered by the essential requirements, the conformity assessment must be revisited. Maintain a change-control process that triggers a compliance review for firmware updates.

