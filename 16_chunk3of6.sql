## Scope and who must comply

The NLF is not a product law in the usual sense. No business complies "with Decision 768/2008" directly. Instead, the Decision provides a toolbox of standard provisions that the EU legislator inserts into product-specific harmonisation legislation, such as the Toy Safety Directive, the Radio Equipment Directive, the Machinery Regulation and the Low Voltage Directive.

The framework defines four economic operators, and these definitions are repeated almost word for word across EU product law:

- **Manufacturer**: any natural or legal person who manufactures a product or has a product designed or manufactured, and markets it under their own name or trademark. The manufacturer carries the primary responsibility for conformity.
- **Authorised representative**: a person established in the EU who has received a written mandate from the manufacturer to act on their behalf for specified tasks, such as keeping the EU Declaration of Conformity and cooperating with authorities.
- **Importer**: a person established in the EU who places a product from a third country on the EU market. Importers must verify that the manufacturer has carried out the correct conformity assessment, that the product bears the required marking, and that traceability information is present.
- **Distributor**: any person in the supply chain, other than the manufacturer or importer, who makes a product available on the market. Distributors must exercise due care, verifying that the product bears the CE marking and is accompanied by the required documents and instructions.

A critical NLF rule is that an importer or distributor who places a product on the market under their own name or trademark, or who modifies a product in a way that may affect its compliance, is treated as the manufacturer and assumes the full set of manufacturer obligations.

## Key obligations under the framework

Because the Decision is a template, its obligations appear inside product-specific legislation. The standard manufacturer obligations derived from the NLF are:

1. Ensure the product is designed and manufactured in accordance with the applicable essential requirements.
2. Draw up the required technical documentation before the product is placed on the market.
3. Carry out (or have carried out) the applicable conformity assessment procedure.
4. Draw up the EU Declaration of Conformity and affix the CE marking where the legislation requires it.
5. Ensure series production remains in conformity, including changes in product design or harmonised standards.
6. Mark the product with a type, batch or serial number and indicate the manufacturer's name, registered trade name or trademark and a contact address.
7. Accompany the product with instructions and safety information in the language(s) of the member state where it is made available.
8. Take corrective action (withdrawal, recall) where a product presents a risk, and inform the competent authorities.

Importer and distributor obligations mirror these at a verification level: importers must not place non-compliant products on the market, must ensure the manufacturer has met the documentation and marking duties, must indicate their own name and address on the product or packaging, and must keep a copy of the EU Declaration of Conformity. Distributors must verify the presence of the CE marking and required documents before making products available, and must cooperate in corrective actions.

## The conformity assessment modules (A to H)

One of the NLF's most practical contributions is the menu of conformity assessment modules, ranging from the manufacturer's self-declaration to full third-party certification:

| Module | Name | Third-party involvement |
|---|---|---|
| A | Internal production control | None (self-declaration) |
| A1 / A2 | Internal production control plus supervised testing | Product testing by an accredited body or notified body |
| B | EU-type examination | Notified body examines a specimen (type) |
| C, C1, C2 | Conformity to type | Follows Module B; C1/C2 add supervised testing |
| D, D1 | Quality assurance of the production process | Notified body approves and surveils the quality system |
| E, E1 | Quality assurance of final product inspection and testing | Notified body approves and surveils the quality system |
| F, F1 | Product verification | Notified body tests every product or statistical batches |
| G | Unit verification | Notified body examines each individual product |
| H, H1 | Full quality assurance (with design examination in H1) | Notified body approves design and quality system |

Each product directive or regulation selects which modules are available for its products. Low-risk products typically allow Module A (self-declaration); higher-risk products require notified body involvement. Businesses must check the applicable product legislation, not the Decision itself, to see which modules apply.

## Documentation and labelling: the CE marking model

The NLF sets the general principles of CE marking, now found in Article 30 of Regulation (EC) No 765/2008 and mirrored in product legislation:

- The CE marking may only be affixed by the manufacturer or their authorised representative.
- It must be affixed before the product is placed on the market, visibly, legibly and indelibly.
- It must follow the prescribed graphic proportions and be at least 5 mm high unless the legislation specifies otherwise.
- Where a notified body was involved in the production-control phase, its identification number follows the CE marking.
- Member states must ensure correct use of the marking and penalise misuse.

The EU Declaration of Conformity must follow the model structure in the Decision: product identification, manufacturer details, the legislation and harmonised standards applied, the notified body details where relevant, and a signed declaration. Technical documentation must be kept for 10 years after the last product is placed on the market (the standard period used across NLF-based legislation).

Traceability is another NLF pillar: economic operators must be able to identify who supplied them and to whom they supplied products, and must keep that information for 10 years.

## Enforcement and penalties

The Decision itself does not set penalties. It requires member states to lay down rules on penalties for infringements of the national provisions adopted pursuant to NLF-based legislation, and those penalties must be effective, proportionate and dissuasive. In practice this means:

- Market surveillance authorities in each member state can require corrective action, order withdrawal or recall, and restrict or prohibit products presenting a risk.
- Serious risks are notified across the EU through the Safety Gate rapid alert system.
- Misuse of the CE marking and failure to draw up or produce the EU Declaration of Conformity are punishable under national law, with sanctions ranging from fines to criminal penalties depending on the member state.

## Staying current

The NLF is a stable framework, but the product legislation built on it changes constantly:

1. Check the product-specific directive or regulation for your product category; that is where the NLF provisions become binding duties with dates and details.
2. Follow harmonised standards published in the Official Journal; they give presumption of conformity with the essential requirements.
3. Watch for revisions of the underlying directives (for example, the shift from directives to regulations in machinery and the proposed Toy Safety Regulation).
4. Monitor the Commission's guidance (the "Blue Guide" on the implementation of EU product rules) for interpretation of NLF concepts such as "placing on the market" and "substantial modification".

## Frequently asked questions

**Does Decision 768/2008/EC apply directly to my product?**
No. It is a framework decision addressed to the EU institutions and member states. Your obligations come from the product-specific directive or regulation that applies to your product, which will incorporate the NLF's standard provisions on operators, modules and CE marking.

**What is the difference between the NLF Decision and Regulation 765/2008?**
They were adopted together as the "goods package". Decision 768/2008 provides the common framework for marketing of products (definitions, modules, CE marking model). Regulation (EC) No 765/2008 sets requirements for accreditation and market surveillance, including the general principles of CE marking in its Article 30.

**I import products from outside the EU and sell them under my own brand. Am I an importer or a manufacturer?**
Under the NLF definitions, you are treated as the manufacturer. Anyone who places a product on the market under their own name or trademark assumes the full manufacturer obligations, including the conformity assessment, technical documentation and EU Declaration of Conformity.

**Do I always need a notified body to affix the CE marking?**
No. Many product laws allow Module A (internal production control, i.e. self-declaration) for lower-risk products. A notified body is only required where the applicable legislation mandates a module involving third-party assessment.

**How long must I keep the technical documentation?**
The NLF model provisions set 10 years from the date the last item of the product was placed on the market. Product-specific legislation may vary this, so confirm in the applicable act.

**Where can I read the official text?**
The authentic text is on EUR-Lex as Decision No 768/2008/EC (CELEX 32008D0768), and the Commission's CE marking pages explain how the framework works in practice.

