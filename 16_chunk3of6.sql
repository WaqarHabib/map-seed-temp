## Scope and who must comply

REACH applies to the manufacture, placing on the market and use of chemical **substances** on their own, in **mixtures**, and in **articles** (objects whose shape or design determines function more than chemical composition, which covers most consumer products). Key roles:

- **Manufacturers and importers of substances** (at or above 1 tonne per year): must register each substance with ECHA, submitting data on properties, uses and safe handling. The phased registration deadlines (2010, 2013, 2018) have all passed; new substances and new market entrants must register before manufacture or import begins ("no data, no market").
- **Downstream users**: businesses using substances in industrial or professional processes must follow the exposure scenarios in suppliers' safety data sheets and communicate their uses up the chain.
- **Suppliers of articles**: any business supplying articles containing substances of very high concern (SVHCs) above 0.1% weight by weight must communicate this down the supply chain and, on consumer request, within 45 days (Article 33). Producers and importers of articles may also have notification duties (Article 7).
- **Only representatives**: non-EU manufacturers can appoint an EU-based only representative to handle registration and importer duties.

Some substances are exempt or partially exempt (for example, certain naturally occurring substances, and substances already regulated under other EU law such as medicines or food), but exemptions are narrow and should be verified case by case.

## Key obligations

**Registration.** Manufacturers and importers of substances at 1 tonne or more per year must submit a technical dossier to ECHA, with data requirements increasing at 10, 100 and 1,000 tonnes per year. Joint submission through Substance Information Exchange Fora (now effectively through lead registrants) shares costs and vertebrate test data.

**Evaluation.** ECHA and member states evaluate dossiers and substances of concern; evaluation can lead to requests for further data or to regulatory risk management.

**Authorisation (Annex XIV).** SVHCs placed on the Authorisation List may not be used or placed on the market after their "sunset date" unless an authorisation has been granted for the specific use. Authorisation is use-specific and time-limited.

**Restriction (Annex XVII).** Currently the most directly relevant part for product businesses: Annex XVII lists restrictions on the manufacture, placing on the market and use of substances in articles. Entries relevant to consumer products include restrictions on nickel in prolonged skin contact items, azo dyes in textiles and leather, PAHs in consumer articles, phthalates in toys and childcare articles, and lead in consumer articles. Restriction entries are added and amended regularly.

**SVHC communication (Articles 7 and 33).** Where an article contains an SVHC on the Candidate List above 0.1% w/w, suppliers must provide recipients with sufficient information for safe use (at minimum the substance name), and consumers must receive the information within 45 days of asking. Producers and importers of articles must notify ECHA where the SVHC exceeds 0.1% w/w and total quantities exceed 1 tonne per year per producer/importer.

**SCIP database.** Under the Waste Framework Directive, suppliers of articles containing Candidate List substances above 0.1% w/w must submit information to ECHA's SCIP database on Substances of Concern In articles, as such or in complex objects (Products). This is an additional notification duty on top of Article 33 communication.

**SCIP database.** Under the Waste Framework Directive, suppliers of articles containing Candidate List substances above 0.1% w/w must submit information to ECHA's SCIP database on Substances of Concern In articles, as such or in complex objects (Products). This is an additional notification duty on top of Article 33 communication.

**Downstream user duties.** Companies that use substances in their processes must check that their use is covered by the exposure scenarios in the safety data sheets they receive. Where it is not, they must either adjust their use, ask the supplier to include it, or carry out their own chemical safety assessment and notify ECHA. These duties are frequently overlooked by product companies that also run manufacturing or finishing processes (coating, plating, adhesives) in-house.

## Conformity process

REACH has no CE marking and no conformity assessment modules. Compliance is demonstrated through:

1. **Substance inventory**: identifying every substance in your products and supply chain, including in purchased articles.
2. **Registration check**: confirming that substances you manufacture or import at 1 tonne or more per year are registered (or covered by your only representative's registration).
3. **Annex XVII screening**: checking each restriction entry against your product's materials and uses.
4. **Candidate List monitoring**: screening bills of materials against the SVHC Candidate List (updated roughly twice a year) for Article 33 and SCIP duties.
5. **Safety data sheets**: obtaining, maintaining and passing on SDSs for hazardous substances and mixtures, and following exposure scenarios as a downstream user.

## Documentation and labelling

- Registration dossiers and evidence of registration (for substance manufacturers/importers).
- Records of Annex XVII compliance assessments per product.
- Article 33 communications and consumer responses (45-day deadline).
- SCIP notifications submitted to ECHA.
- Safety data sheets and exposure scenario compliance records (for downstream users).
- Classification and labelling under the CLP Regulation (EC) No 1272/2008, which works alongside REACH for hazard communication.

Records should be kept for at least 10 years after the last manufacture, import, supply or use of the substance or article.

## Enforcement and penalties

- Enforcement is national: each member state designates authorities and inspectors, coordinated through ECHA's Forum for Exchange of Information on Enforcement.
- Penalties must be effective, proportionate and dissuasive; they include fines and criminal sanctions varying by member state.
- Common enforcement targets include Annex XVII restrictions in imported consumer products (textiles, jewellery, toys) and missing Article 33 communication.
- ECHA's enforcement forum runs coordinated EU-wide projects (such as REACH-EN-FORCE) focusing on specific restriction entries.

## Staying current

1. Check the **consolidated** REACH text on EUR-Lex before relying on any Annex XVII entry; restrictions change frequently.
2. Screen against each Candidate List update (typically June and December); a new listing can create Article 33 and SCIP duties overnight.
3. Track the Commission's REACH revision work, which may reshape registration, mixture assessment and digital information duties.
4. Coordinate REACH screening with RoHS, Toy Safety and GPSR substance work to avoid duplicate supplier outreach.
5. Remember that REACH duties apply to articles regardless of origin: imported articles must meet Annex XVII and Article 33 duties just like EU-made ones, so importers need the same substance data as manufacturers.

## Frequently asked questions

**I only sell finished consumer products. Does REACH apply to me?**
Yes, through Annex XVII restrictions (which can ban or limit substances in your articles), Article 33 SVHC communication duties, and SCIP notification duties. You do not need to register substances unless you manufacture or import the substances themselves at 1 tonne or more per year.

**What is an SVHC and where is the list?**
A substance of very high concern: carcinogenic, mutagenic or reprotoxic, persistent/bioaccumulative/toxic, or of equivalent concern (such as endocrine disruptors). ECHA publishes the Candidate List; inclusion triggers Article 33 communication duties above 0.1% w/w in articles.

**What is the 45-day rule?**
Under Article 33(2), any consumer may ask whether an article contains an SVHC above 0.1% w/w, and the supplier must answer free of charge within 45 days. Businesses need a process to answer these requests, since they can arrive at any time.

**What is the difference between restriction and authorisation?**
Restriction (Annex XVII) bans or limits specific uses of a substance for everyone. Authorisation (Annex XIV) requires companies to apply for permission to continue specific uses of listed SVHCs after a sunset date. Both can apply to the same substance.

**Do I need to register if my non-EU supplier is registered?**
No, but only if your non-EU manufacturer has appointed an EU-based only representative who has registered the substance covering your import quantities. Otherwise, as the EU importer you are the registrant. Confirm the arrangement in writing.

