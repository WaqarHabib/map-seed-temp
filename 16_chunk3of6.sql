**Short answer:** Regulation (EU) 2025/40, the Packaging and Packaging Waste Regulation (PPWR), is the EU's directly applicable framework for packaging sustainability. Published in January 2025 and generally applying from 12 August 2026, it sets substance restrictions, design-for-recycling requirements, recycled content targets for plastic packaging, extended producer responsibility, harmonised labelling (including QR codes), deposit return schemes for beverage containers, and bans on certain single-use formats. It affects any business placing packaged products on the EU market.

