**Short answer:** Decision No 768/2008/EC is the EU's common framework for the marketing of products, better known as the New Legislative Framework (NLF). It defines who the economic operators are (manufacturer, authorised representative, importer, distributor), sets the standard modules for conformity assessment (A to H), and provides the model rules on CE marking, traceability and technical documentation that EU product directives and regulations copy into their own texts. It affects any business placing manufactured products on the EU market.

