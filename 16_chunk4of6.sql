## Frequently asked questions

**I sell EEE online from outside the EU to EU customers. Do I need to register?**
Yes. Distance sellers are producers in the member state of the customer and must register there, appointing an authorised representative established in that member state to fulfil the obligations.

**Is there one EU-wide WEEE registration?**
No. Registration is national, in each member state where you place EEE on the market. There is no single EU registration covering all countries.

**What does the crossed-out wheeled bin symbol mean?**
It indicates the product must not be disposed of with unsorted household waste but collected separately for treatment. The EN 50419 standard specifies the marking, and many producers add a date mark (a bar or date code) showing when the product was placed on the market.

**Do I need to join a scheme, or can I comply individually?**
Both are possible. Most producers join a collective compliance scheme, which is simpler and cheaper at small volumes. Individual schemes are permitted but must meet the same collection and treatment obligations.

**What are the collection targets?**
Member states must collect at least 65% of the average weight of EEE placed on the market in the preceding three years (or 85% of WEEE generated). Producers contribute through their schemes' collection networks.

