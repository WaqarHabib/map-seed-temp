**Short answer:** Directive 2009/48/EC is the EU's sector law for toys, setting essential safety requirements covering physical, mechanical, flammability, chemical, electrical, hygiene and radioactivity hazards, plus mandatory warnings and CE marking. It applies to any product designed or intended for play by children under 14 placed on the EU market. Manufacturers, importers and distributors of toys must meet its requirements, with chemical limits among the strictest in EU product law.

