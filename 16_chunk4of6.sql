## What EUR-Lex contains and why it matters

Product compliance work constantly raises the same question: "what does the law actually require, as in force today?" EUR-Lex answers it with several document types:

- **Official Journal (OJ)**: the authentic publication of EU legislation. The L series carries legislation; the C series carries notices, preparatory acts and announcements. Since 1 July 2013 the electronic edition of the OJ has been the authentic version.
- **Original acts**: regulations, directives and decisions as adopted, with their CELEX numbers.
- **Consolidated versions**: the original act with all subsequent amendments integrated into a single readable text. These are marked as for information only (the authentic texts remain the OJ publications), but they are the practical working reference for amended acts such as REACH or the Toy Safety Directive.
- **National transposition measures**: for directives, EUR-Lex links to the national implementing measures notified by member states (via the N-Lex connections).
- **Case law**: judgments of the Court of Justice of the European Union, which interpret EU product law authoritatively.
- **Summaries of EU legislation**: plain-language overviews of key acts, useful as a starting point before reading the legal text.
- **ELI (European Legislation Identifier)**: stable URIs for legislation, such as https://eur-lex.europa.eu/eli/reg/2024/1781/oj.

## How to use EUR-Lex for product compliance

**Finding an act.** Search by CELEX number (for example, 32023R0988 for the GPSR), by act number and year (2023/988), or by title keywords. The CELEX number encodes the act: the first digit indicates the sector (3 for legislation), followed by the year, the type letter (R for regulation, L for directive, D for decision) and the number.

**Checking what is in force.** Every act page shows its dates (entry into force, application, end of validity), its legal status, and crucially the **"consolidated versions"** tab listing the current consolidated text. For heavily amended acts, always work from the latest consolidated version rather than the original.

**Tracking amendments.** The "document information" and "procedure" tabs show amending acts, corrigenda and the legislative procedure history. Setting up an RSS feed or monitoring the OJ for your product area catches new delegated acts and amendments.

**Checking transposition.** For directives, the national transposition tab shows how each member state implemented the act, with links to national measures. This matters because obligations such as penalties and enforcement procedures live in national law.

**Using standards references.** Harmonised standards giving presumption of conformity are published as Commission implementing decisions or communications in the OJ; EUR-Lex is where their references and dates are officially recorded.

## CELEX and ELI URL patterns

Two URL patterns cover most compliance needs:

- CELEX pattern: `https://eur-lex.europa.eu/legal-content/EN/TXT/?uri=CELEX:<celex>` (for example, CELEX:32023R0988). The language code can be changed (FR, DE and others).
- ELI pattern: `https://eur-lex.europa.eu/eli/reg/<year>/<number>/oj` for regulations, with analogous patterns for directives (`/dir/`) and decisions (`/dec/`).

Both patterns are stable and suitable for linking from compliance documentation and product files.

## Worked example: tracing a product rule from question to answer

Suppose you sell a connected toy and need to know which EU rules apply and what they currently require:

1. **Identify candidate acts** via the Commission's sector pages or EUR-Lex search: the Toy Safety Directive (2009/48/EC), the Radio Equipment Directive (2014/53/EU) and REACH (1907/2006) are candidates.
2. **Open each act's EUR-Lex page** via its CELEX number and check the status line: is it in force, and what are its application dates?
3. **Open the latest consolidated version** of each act and read the scope articles to confirm your product is covered.
4. **Check the amendments tab** for recent changes: for toys, Annex II chemical amendments; for RED, the 2022/2380 common charger amendment and the 2022/30 cybersecurity delegated regulation.
5. **Check harmonised standards references** in the OJ for presumption of conformity (EN 71 for toys, ETSI standards for radio).
6. **Check national transposition** for the directives to find the penalty and enforcement rules in your member states of sale.
7. **Record your sources**: note the CELEX numbers, consolidated version dates and OJ references in your technical file, so the compliance basis is auditable years later.

This workflow, repeated for each product category, is the backbone of EU product compliance research.

## The Official Journal structure

Understanding the OJ's structure helps you read EUR-Lex references correctly:

- **L series (Legislation)**: binding acts. Citations look like "OJ L 191, 28.7.2023": the L series, issue 191, dated 28 July 2023. Page numbers within the issue pinpoint the act.
- **C series (Information and notices)**: non-binding content, including harmonised standard references, calls and announcements.
- **Special editions**: the OJ is published daily on working days; there is no longer a meaningful print edition, and the electronic edition has been authentic since 1 July 2013.

When a regulation cites its own publication ("Done at Brussels..."), the OJ reference is the canonical citation for legal and compliance documentation.

## Practical tips and limitations

- **Consolidated versions lag**: after a new amendment is published, the consolidated text takes time to appear. For the very latest changes, read the amending act itself.
- **Corrigenda matter**: check for corrigenda (corrections) to the act, which can change substantive provisions.
- **Language versions**: all 24 language versions are equally authentic; where translations differ, the Court of Justice resolves the meaning, but for compliance work the English version is normally sufficient.
- **No legal advice**: EUR-Lex provides the texts, not interpretation. Complex questions (such as whether your product falls within a directive's scope) may need expert review.
- **Complementary sources**: EUR-Lex gives the law; the Commission's sector pages, guidance documents (such as the Blue Guide on product rules) and harmonised standards provide the operational detail.

## EUR-Lex for non-EU businesses

If you manufacture outside the EU and sell into it, EUR-Lex is still your primary source. EU product law applies to products placed on the EU market regardless of where they are made, and your EU importer, authorised representative or responsible operator will expect you to understand the applicable acts. Practical approach: identify the CELEX numbers for your product categories, work from consolidated versions, and align your technical files and declarations of conformity to the cited OJ references. Where language is a barrier, the Commission's sector pages and guidance documents summarise the operational requirements, but the EUR-Lex text remains the authority when questions arise.

## Staying current with EUR-Lex

1. Bookmark the consolidated versions of the acts governing your products and re-check them on a schedule (for example, quarterly), since amendments arrive without direct notification to businesses.
2. Use the OJ's daily feed or EUR-Lex search alerts for new acts in your sector.
3. When citing legislation in declarations of conformity or technical files, cite the act number, OJ reference and the consolidated version date you relied on.
4. For directives, verify national transposition in each member state of sale, because enforcement and penalties are national.

## Frequently asked questions

**Is EUR-Lex free to use?**
Yes. All content on EUR-Lex is freely accessible, in all 24 official EU languages.

**What is a CELEX number?**
A unique identifier for each EU legal document. For legislation it encodes the sector, year, type and number: 32023R0988 means sector 3 (legislation), year 2023, R (regulation), number 988.

**Can I rely on the consolidated version in a legal dispute?**
Consolidated versions are explicitly for information purposes; the authentic texts are the Official Journal publications (including amending acts and corrigenda). For compliance work they are the standard reference, but legal proceedings rely on the authentic texts.

**How do I find whether a directive has been transposed in a specific country?**
Open the directive's EUR-Lex page and use the national transposition tab, which lists the measures notified by each member state with links to national sources.

**What is the difference between the L and C series of the Official Journal?**
The L series publishes binding legislation (regulations, directives, decisions). The C series publishes information, notices, preparatory legislative documents and announcements such as harmonised standard references.

**Does EUR-Lex include harmonised standards?**
It publishes the references to harmonised standards (the Commission decisions and communications listing them), which is what gives presumption of conformity. The standards texts themselves are sold by the standards bodies (CEN, CENELEC, ETSI).

