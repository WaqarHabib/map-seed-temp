## Chemical requirements in practice

The chemical regime is where most toy compliance effort goes. Key elements include:

- **Migration limits**: Annex II, Part III sets migration limits for 19 elements from toy materials, differentiated by material type (dry, liquid, scraped-off). Lead, cadmium and mercury limits are particularly strict, and limits for toys intended for children under 36 months or intended to be placed in the mouth are tighter.
- **CMR substances**: substances classified as carcinogenic, mutagenic or toxic for reproduction of category 1A, 1B or 2 are generally prohibited in toys, in components and in micro-structurally distinct parts, with limited exemptions subject to strict conditions.
- **Fragrance allergens**: Annex II lists prohibited allergenic fragrances and those requiring labelling when present above 100 mg/kg. The list has been expanded by amendments, so the consolidated text is the only safe reference.
- **Nitrosamines**: strict limits apply to toys for children under 36 months and toys intended to be placed in the mouth that are made of rubber or contain rubber parts.

Because limits and listed substances change through amendments, testing strategies should be built against the current consolidated directive and the applicable EN 71 parts, not against a printed copy of the original 2009 text.

## Staying current

1. Check the consolidated version of the directive on EUR-Lex before relying on chemical limits; Annex II has been amended many times (elements, allergenic fragrances, CMR substances).
2. Track the proposed Toy Safety Regulation, which would convert the rules into a regulation and add a digital product passport.
3. Follow the EN 71 series updates; new or revised harmonised standards change the presumption of conformity.
4. Monitor Safety Gate notifications for toys to see which hazards authorities are targeting.

## Frequently asked questions

**What counts as a toy?**
Any product designed or intended, whether exclusively or not, for use in play by children under 14. Products listed in Annex I (such as public playground equipment and certain sports goods) are excluded. Borderline products should be assessed against Commission guidance and, where uncertain, expert review.

**When is a notified body required for toys?**
When harmonised standards covering all applicable safety requirements have not been used (or do not exist), the manufacturer must use EC-type examination (Module B) by a notified body together with conformity to type (Module C). Full application of the EN 71 standards allows self-declaration under Module A.

**What is the "under 36 months" warning rule?**
Toys that are not intended for children under 36 months but might appeal to them must carry the warning "Not suitable for children under 36 months" (or equivalent), with a brief statement of the hazard. Misuse of this warning, including omitting it where required, is a frequent cause of enforcement action.

**Are the chemical limits the same as REACH?**
No. The Toy Safety Directive has its own chemical regime in Annex II (migration limits for 19 elements, CMR restrictions, fragrance rules), which applies in addition to REACH restrictions such as those in Annex XVII. Both must be satisfied.

**Is the directive being replaced?**
The Commission proposed a Toy Safety Regulation in July 2023 to replace the directive. Until it is adopted and applies, the directive remains the binding law. Businesses should track the proposal because it would introduce stricter chemical provisions and a digital product passport for toys.

