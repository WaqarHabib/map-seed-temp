|---|---|
| Jurisdiction | European Union |
| Authority | European Parliament and Council of the EU |
| Instrument type | Directive (transposed nationally; registers and schemes are national) |
| Reference | Directive 2012/19/EU (recast) |
| Adopted | 4 July 2012 |
| Published | Official Journal L 197, 24 July 2012 |
| Scope | 6 product categories under "open scope" since 15 August 2018 |
| CELEX | 32012L0019 |

## Scope and who must comply

WEEE applies to EEE: equipment dependent on electric currents or electromagnetic fields to work properly, and equipment for the generation, transfer and measurement of such currents and fields, designed for use with a voltage rating not exceeding 1,000 V AC or 1,500 V DC. From 15 August 2018 the directive has **open scope** with 6 categories:

1. Temperature exchange equipment (fridges, air conditioners, heat pumps)
2. Screens and monitors (equipment with screens over 100 cm2)
3. Lamps
4. Large equipment (any external dimension over 50 cm: washing machines, printers, PV panels)
5. Small equipment (no external dimension over 50 cm: vacuum cleaners, microwaves, toys)
6. Small IT and telecommunications equipment (no external dimension over 50 cm: phones, laptops, routers)

A **producer** is any person who manufactures, resells under their own brand, or imports EEE into a member state, or who sells EEE by distance directly to end users in a member state. Distance sellers are explicitly covered: selling online into a member state makes you the producer there, with registration duties even if you have no local establishment (fulfilled through an authorised representative).

## Key obligations

**Producer registration.** Producers must register in **each member state** where they place EEE on the market, through the national register (for example, the EAR in Germany, SYDEREP in France, the national WEEE registers elsewhere). Registration requires reporting the quantities of EEE placed on the market by category. Distance sellers must appoint an authorised representative established in the member state of sale to handle registration and obligations.

**Financing collection and treatment.** Producers must finance the collection of WEEE from collection facilities and its proper treatment, recovery and disposal. In practice this is done by joining a **producer compliance scheme** (a collective organisation that organises collection and treatment on members' behalf) or, for large producers, operating an individual scheme. The costs are typically charged per unit or per kilogram placed on the market.

**Collection targets.** From 2019, member states must achieve an annual collection rate of at least **65% of the average weight of EEE placed on the market in the three preceding years**, or alternatively 85% of WEEE generated on their territory. Producers, through their schemes, must contribute to meeting these targets.

**Treatment standards.** WEEE must be treated using best available techniques, with removal of specified substances, mixtures and components (batteries, mercury-containing components, capacitors and similar) before further treatment. Minimum recovery and recycling targets apply per category, and treatment facilities must meet the technical requirements in Annexes VII and VIII.

**Information duties.** Producers must provide treatment facilities with information on preparation for reuse and treatment (generally through information platforms or upon request), and must mark EEE with the crossed-out wheeled bin symbol per EN 50419, preferably with a date mark identifying when the product was placed on the market.

**Treatment chain.** Collected WEEE flows from municipal collection points and retailers to treatment facilities, where depollution (removal of batteries, capacitors, mercury components and other hazardous fractions) precedes shredding, sorting and material recovery. Producers' schemes contract with treatment operators and must demonstrate that treatment meets the directive's technical requirements and recovery targets. Export of WEEE for treatment outside the EU is subject to strict shipment rules, and only properly documented treatment counts toward targets.

## National registers and schemes: what differs in practice

Because the directive is transposed nationally, the day-to-day experience of compliance varies significantly by member state:

- **Register mechanics**: some registers are run by environmental agencies, others by private bodies under government mandate. Registration data required, reporting periods (monthly, quarterly, annual) and fee structures differ.
- **Scheme markets**: some member states have a single dominant compliance scheme; others (notably Germany and France) have competing schemes, and producers can choose between them on price and service.
- **Authorised representative rules**: the conditions for appointing an authorised representative, and what the representative must do beyond registration (reporting, guaranteeing financing), vary nationally.
- **Enforcement intensity**: some member states actively cross-check marketplace listings against register data and block unregistered sellers; others rely more on audits.

The practical consequence is that WEEE compliance cannot be centralised into a single EU filing. Businesses typically work with a compliance service provider that manages registrations, authorised representatives and scheme contracts across all member states of sale, or they build equivalent in-house capacity country by country.

## Conformity process

WEEE has no CE marking and no conformity assessment modules. Compliance is administrative and organisational:

1. Determine producer status in each member state of sale (including distance sales).
2. Register with the national register, directly or through an authorised representative.
3. Join a producer compliance scheme (or set up an individual scheme) and contractually allocate financing.
4. Report quantities placed on the market by category and reporting period.
5. Mark products with the crossed-out wheeled bin symbol.
6. Provide treatment information to recyclers.
7. Keep records of quantities, scheme membership and treatment evidence for inspection.

## Documentation and labelling

- National producer registration numbers for each member state.
- Scheme membership contracts and fee records.
- Periodic quantity reports by WEEE category.
- The crossed-out wheeled bin symbol on products (EN 50419), with date marking where applied.
- Treatment and recycling evidence from scheme operators.
- Records retained for the periods required by national law (commonly several years).

## Enforcement and penalties

- National registers can block market access: selling EEE without registration is prohibited, and several member states empower authorities or marketplaces to stop sales by unregistered producers.
- Authorities audit quantity reports and scheme financing; under-reporting quantities is a common enforcement target.
- Penalties are national and must be effective, proportionate and dissuasive, including fines and sales bans.
- Distance sellers are an enforcement priority, with authorised-representative requirements actively policed at the border and online.

