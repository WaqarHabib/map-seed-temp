**Short answer:** The RoHS Directive (2011/65/EU) restricts ten hazardous substances in electrical and electronic equipment (EEE) placed on the EU market: lead, mercury, cadmium, hexavalent chromium, PBB, PBDE and four phthalates (DEHP, BBP, DBP, DIBP), with maximum concentration values of 0.1% (0.01% for cadmium) by weight in homogeneous materials. It affects manufacturers, importers and distributors of EEE, who must also CE-mark products, draw up an EU Declaration of Conformity and keep technical documentation.

