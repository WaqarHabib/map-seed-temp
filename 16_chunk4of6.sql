## Staying current

1. Always work from the consolidated directive text; exemptions in Annexes III and IV change regularly.
2. Track exemption expiry dates in your bill of materials; a lapsed exemption means redesign or re-qualification.
3. Monitor Commission reviews of the substance list; additional substances have been repeatedly discussed.
4. Align RoHS documentation (EN IEC 63000) with REACH and SCIP data collection to avoid duplicating supplier outreach.

## Frequently asked questions

**Does the 0.1% limit apply to the whole product or to each material?**
To each homogeneous material: any material of uniform composition throughout that cannot be mechanically separated into different materials. A compliant product can therefore contain a restricted substance in one homogeneous material only up to the limit for that material.

**Do I need a notified body for RoHS?**
No. RoHS conformity assessment is internal production control (Module A) based on technical documentation per EN IEC 63000. No third-party certification is required by the directive, though customers may demand test reports.

**What is the difference between RoHS 2 and RoHS 3?**
RoHS 2 is the 2011 recast (2011/65/EU). "RoHS 3" is the informal name for the amendment by Directive (EU) 2015/863, which added the four phthalates (DEHP, BBP, DBP, DIBP) to the restricted substance list.

**Are spare parts covered?**
Yes. Cables and spare parts for the repair, reuse, updating of functionalities or upgrading of capacity of EEE must also comply with the substance restrictions.

**Can I rely on supplier declarations alone?**
Supplier declarations are the standard starting point, but the manufacturer remains responsible for conformity. A risk-based approach combines declarations with screening or confirmatory testing, particularly for high-risk materials and new suppliers.

