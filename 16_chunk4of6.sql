**Short answer:** The WEEE Directive (2012/19/EU) makes producers of electrical and electronic equipment (EEE) responsible for financing the collection, treatment and recycling of waste EEE in the EU. Producers must register in each member state where they place EEE on the market, join or operate collection schemes, mark products with the crossed-out wheeled bin symbol, and meet binding collection targets. It affects any business placing EEE on EU markets, including distance sellers who must appoint authorised representatives for registration.

