## Scope and who must comply

RoHS applies to EEE: equipment dependent on electric currents or electromagnetic fields to work properly, and equipment for the generation, transfer and measurement of such currents and fields. Since 22 July 2019 the directive has **open scope**: all EEE falls within scope unless specifically excluded. The 11 categories are:

1. Large household appliances
2. Small household appliances
3. IT and telecommunications equipment
4. Consumer equipment
5. Lighting equipment
6. Electrical and electronic tools
7. Toys, leisure and sports equipment
8. Medical devices
9. Monitoring and control instruments (including industrial)
10. Automatic dispensers
11. Other EEE not covered by categories 1 to 10

Exclusions include equipment for military or space purposes, large-scale stationary industrial tools, large-scale fixed installations, means of transport (with exceptions), non-road mobile machinery, active implantable medical devices, photovoltaic panels for public/commercial/industrial/residential energy use, and equipment designed solely for research and development.

Manufacturers, authorised representatives, importers and distributors have the standard NLF-structured duties, adapted to substance restrictions.

## Key obligations: the substance restrictions

The core rule (Article 4): EEE placed on the market, including cables and spare parts for repair, reuse, updating or upgrading, must not contain the restricted substances above the maximum concentration values **by weight in homogeneous materials**:

| Substance | Maximum concentration |
|---|---|
| Lead (Pb) | 0.1% |
| Mercury (Hg) | 0.1% |
| Cadmium (Cd) | 0.01% |
| Hexavalent chromium (Cr(VI)) | 0.1% |
| Polybrominated biphenyls (PBB) | 0.1% |
| Polybrominated diphenyl ethers (PBDE) | 0.1% |
| Bis(2-ethylhexyl) phthalate (DEHP) | 0.1% |
| Butyl benzyl phthalate (BBP) | 0.1% |
| Dibutyl phthalate (DBP) | 0.1% |
| Diisobutyl phthalate (DIBP) | 0.1% |

The four phthalates were added by Directive (EU) 2015/863 ("RoHS 3") and apply to all EEE from 22 July 2019 (medical devices and monitoring and control instruments from 22 July 2021). The "homogeneous material" concept is critical: the limit applies to each material of uniform composition that cannot be mechanically separated (for example, the plastic housing as distinct from its coating), not to the finished product as a whole.

**Exemptions.** Annex III lists applications exempted from the restrictions (for example, lead in certain alloys, mercury in certain lamps), and Annex IV lists exemptions specific to medical devices and monitoring and control instruments. Exemptions are time-limited and must be renewed; businesses must check the current consolidated text because expired exemptions cannot be relied upon.

**Exemptions.** Annex III lists applications exempted from the restrictions (for example, lead in certain alloys, mercury in certain lamps), and Annex IV lists exemptions specific to medical devices and monitoring and control instruments. Exemptions are time-limited and must be renewed; businesses must check the current consolidated text because expired exemptions cannot be relied upon.

Exemption management deserves its own process. Each exemption has a defined scope (specific application and material), a maximum concentration where relevant, and an expiry date, and renewal applications must be submitted well before expiry with technical justification. Many businesses maintain an exemption register linked to their bill of materials, flagging exemptions due to expire within 18 months so that re-qualification, redesign or renewal applications can be planned. Relying on an expired exemption is treated the same as any other non-compliance.

## RoHS in the supply chain: a practical approach

Because RoHS compliance is demonstrated by the manufacturer through technical documentation rather than third-party certification, the quality of supply chain evidence is decisive:

1. **Collect material declarations** from every supplier, ideally in a standardised format such as IPC-1752A declarations, identifying homogeneous materials and their substance content.
2. **Risk-rank components**: connectors, solders, coatings, plastics with flame retardants and recycled-content materials warrant closer scrutiny than simple mechanical parts.
3. **Screen and test**: XRF screening identifies suspect materials quickly; confirmatory testing to IEC 62321 series methods resolves borderline or high-risk cases.
4. **Document exemptions explicitly**: where you rely on an Annex III or IV exemption, record the exemption number, scope and expiry against the affected part.
5. **Re-verify on change**: any change of supplier, material, plating or formulation restarts the assessment for the affected homogeneous materials.

Large customers will typically audit this file, so building it to the EN IEC 63000 structure from the start saves repeated rework.

## Conformity process

1. **Substance assessment**: the manufacturer assesses every homogeneous material in the product against the restricted substance list, typically through supplier declarations, material declarations and analytical testing (for example, XRF screening followed by confirmatory wet-chemical testing to IEC 62321 methods).
2. **Harmonised standard**: EN IEC 63000 provides the technical documentation framework for the assessment of EEE with respect to substance restrictions and gives presumption of conformity.
3. **Internal production control (Module A)**: RoHS uses manufacturer self-declaration; no notified body is involved.
4. **EU Declaration of Conformity and CE marking**: the manufacturer draws up the EU DoC (covering RoHS alongside other applicable legislation) and affixes the CE marking.

Importers must verify the manufacturer has carried out the assessment and that the product bears the CE marking and required traceability information. Distributors must exercise due care.

## Documentation and labelling

- **Technical documentation** per EN IEC 63000: product description, materials and parts information, supplier declarations, test results, and the basis for any exemption relied upon. Keep for 10 years after the last product is placed on the market.
- **EU Declaration of Conformity** identifying the product, the manufacturer, the legislation applied and the standards used.
- **CE marking** affixed visibly, legibly and indelibly.
- **Traceability**: type, batch or serial number; manufacturer's name, registered trade name or trademark and contact address; importer's details where applicable.

## Enforcement and penalties

- National market surveillance authorities test products for restricted substances, often using XRF screening at the border or in the market.
- Non-compliant products can be ordered withdrawn or recalled; serious cases are notified through Safety Gate.
- Penalties are national and must be effective, proportionate and dissuasive, including fines and in some member states criminal sanctions.
- Supply chain pressure is a major enforcement channel in practice: large customers routinely demand RoHS compliance declarations and test reports from suppliers.

