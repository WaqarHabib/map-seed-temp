## Scope and who must comply

A "toy" is any product designed or intended, whether or not exclusively, for use in play by children under 14 years of age. The directive applies to manufacturers, authorised representatives, importers and distributors of toys placed on the EU market, with the standard NLF division of responsibilities.

Excluded products include playground equipment for public use, automatic playing machines for public use, toy vehicles with combustion engines, toy steam engines, slings and catapults, and certain other categories listed in Annex I. Products such as children's books, puzzles above certain piece counts and sports equipment fall outside the toy definition where they are not intended for play by under-14s.

Because it is a directive, the binding rules are the national transpositions in each member state, but the requirements are harmonised and the directive's text is the authoritative reference. Note: the Commission has proposed replacing the directive with a directly applicable **Toy Safety Regulation** (proposal of July 2023), which would introduce stricter chemical rules and a digital product passport for toys. Businesses should track that proposal alongside the current directive.

## Key obligations

**Essential safety requirements (Annex II).** Toys must satisfy the general safety obligation and the particular safety requirements covering:

- **Physical and mechanical properties**: no sharp edges or points, protection against strangulation, suffocation and choking (including small-parts rules for toys intended for children under 36 months), projectile requirements, and stability.
- **Flammability**: toys must not constitute a dangerous flammable element; specific rules apply to beards, wigs, masks, costumes and toys children can enter.
- **Chemical properties**: migration limits for 19 elements (including lead, cadmium, mercury and chromium), restrictions on CMR substances (carcinogenic, mutagenic or toxic for reproduction), nitrosamine and nitrosatable substance limits for rubber toys for under-3s, and fragrance allergen rules.
- **Electrical properties**: limited to nominal voltages of 24 V DC (or equivalent AC), with requirements on insulation, heat and battery safety.
- **Hygiene and radioactivity**: toys must meet hygiene and cleanliness requirements; radioactivity must comply with Euratom standards.

**Warnings (Article 11).** Toys must carry warnings where needed for safe use, including:

- Toys not intended for children under 36 months (or 3 years) must bear a warning such as "Not suitable for children under 36 months" or "Not suitable for children under 3 years", with a brief indication of the specific hazard. This is one of the most frequently enforced labelling rules in the EU.
- Category-specific warnings apply to functional toys, chemical toys, skates and skateboards, aquatic toys, toys in food and similar categories.
- Warnings must be clearly visible, easily legible, in the language(s) of the member state of sale, and must not conflict with the intended use of the toy.

## Conformity process

1. **Safety assessment**: the manufacturer must carry out an analysis of the chemical, physical, mechanical, electrical, flammability, hygiene and radioactivity hazards the toy may present, and assess exposure to such hazards (Article 18).
2. **Harmonised standards**: compliance with harmonised standards published in the Official Journal (the **EN 71 series**, covering mechanical/physical properties, flammability, migration of certain elements and other aspects) gives presumption of conformity with the corresponding essential requirements.
3. **Conformity assessment**: where harmonised standards covering all relevant safety requirements have been applied, the manufacturer may use internal production control (Module A, self-declaration). Where standards have not been applied, or only partly, or where no standards exist, **EC-type examination (Module B)** by a notified body plus conformity to type (Module C) is required.
4. **CE marking**: the manufacturer affixes the CE marking before placing the toy on the market, draws up the EU Declaration of Conformity and keeps the technical documentation (including the safety assessment) for 10 years.

Importers must verify that the manufacturer has carried out the assessment, that the toy bears the CE marking and required warnings, and that traceability details are present. Distributors must exercise due care before making toys available.

## Documentation and labelling

- **EU Declaration of Conformity** following the model structure, kept with the technical documentation for 10 years.
- **Technical documentation** including the design and manufacturing description, the safety assessment, test reports, and the list of harmonised standards applied.
- **Traceability**: type, batch, serial or model number plus the manufacturer's name, registered trade name or trademark and contact address on the toy (or packaging/documents where size or nature requires); importer's details added where applicable.
- **Instructions and safety information** in the language(s) of the member state where the toy is made available.

## Enforcement and penalties

- National market surveillance authorities test toys routinely; toys are consistently among the most-notified product categories in the Safety Gate rapid alert system, particularly for choking hazards, chemical exceedances and missing warnings.
- Non-compliant toys can be ordered withdrawn or recalled, and serious risks trigger EU-wide alerts.
- Penalties are set by member states and must be effective, proportionate and dissuasive; they include fines and, in some member states, criminal sanctions.

