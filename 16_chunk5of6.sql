**Short answer:** The Electrical Equipment (Safety) Regulations 2016 (SI 2016/1101) are the UK's safety law for electrical equipment placed on the market in Great Britain. Made on 15 November 2016 and in force from 8 December 2016, they transpose the EU Low Voltage Directive's safety objectives into UK law, requiring electrical equipment to be safe, to carry UKCA marking (or CE marking where recognised), and to be supported by technical documentation and a declaration of conformity. They affect manufacturers, importers and distributors of electrical equipment for the GB market.

