Yes. Northern Ireland follows EU product rules under the Windsor Framework. Goods placed on the NI market generally need CE marking (with UKNI marking in certain cases involving UK bodies), and GB rules do not apply there.

**Where do I find the actual laws?**
On legislation.gov.uk, which publishes the authoritative texts of UK statutory instruments. GOV.UK guidance explains them but the legislation is the authority.

**What is the General Product Safety Regulations 2005?**
The UK's general product safety net for consumer products not covered by sector-specific regulations, requiring that products placed on the market are safe and imposing traceability and corrective-action duties. Reform of the general framework has been under discussion alongside the Product Regulation and Metrology Bill.

