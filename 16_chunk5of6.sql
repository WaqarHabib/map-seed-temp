## The regulator's role

Health Canada's Consumer Product Safety Program works across the product lifecycle:

- **Rulemaking**: developing and maintaining product-specific regulations under the CCPSA (children's products, corded window coverings, chemical consumer products, textiles flammability and others), updating them as risks and standards evolve.
- **Market surveillance**: monitoring the marketplace through inspections, sampling and testing, targeted surveillance projects, and analysis of incident reports and consumer complaints.
- **Import surveillance**: working with the Canada Border Services Agency to identify and stop non-compliant consumer products at the border.
- **Incident response**: receiving mandatory incident reports from industry (2-day initial, 10-day written reports under section 14 of the CCPSA) and consumer reports, investigating, and determining corrective action.
- **Recalls and alerts**: negotiating voluntary recalls with firms, issuing recall orders where necessary, and publishing recalls and safety alerts in the public database.
- **Education**: publishing guidance for industry and consumers on product safety requirements and safe use.

Understanding this structure helps businesses interact with the right part of the organisation: regulatory questions go to the program's guidance channels, incidents go through the reporting system, and enforcement matters are handled by inspectors and compliance officers.

## What Health Canada expects from industry

**Know your product's regulations.** Beyond the CCPSA's general prohibition on dangerous products, Health Canada expects businesses to identify and comply with every product-specific regulation applying to their goods. The department publishes guidance documents and regulatory summaries, but the legal obligation sits with the business.

**Report incidents on time.** The 2-day/10-day reporting clock under section 14 starts when the business becomes aware of the incident. Health Canada expects businesses to have internal procedures that identify reportable incidents quickly, including from customer complaints, warranty claims and social media, not only from formal legal claims.

**Cooperate with inspections and recalls.** Inspectors may enter premises, examine and sample products, and require documents. When Health Canada seeks a voluntary recall, it expects prompt cooperation on scope, remedy and public communication. Recall orders follow where cooperation is absent or insufficient.

**Notify cosmetics.** The Cosmetics Program expects notification within 10 days after first sale in Canada, with formulations screened against the Cosmetic Ingredient Hotlist. Health Canada reviews notifications and can request additional information or take action on non-compliant products.

**Maintain traceability.** Health Canada expects commercial manufacturers, importers and sellers to keep records identifying products, suppliers, customers and supply periods, and to produce them on request. This is the foundation of effective recalls.

## Recalls and safety alerts: how the system works

1. **Signal**: Health Canada learns of a potential problem through incident reports, consumer complaints, import surveillance, marketplace monitoring or information from foreign regulators.
2. **Assessment**: the department evaluates the risk, which may involve product testing and consultation with the firm.
3. **Corrective action**: Health Canada seeks a voluntary recall or other corrective measures from the responsible firm, agreeing on the scope (models, date ranges), the remedy (refund, repair, replacement) and the public notice.
4. **Publication**: the recall is published in the Recalls and Safety Alerts database with product identification, hazard description and remedy instructions.
5. **Monitoring**: Health Canada monitors the recall's effectiveness and can escalate to orders or enforcement action if the firm does not comply.

Consumers and businesses can subscribe to recall alerts. For industry, monitoring recalls in your product category is a practical way to calibrate your own risk assessments and see which hazards Health Canada is targeting.

## Enforcement approach

Health Canada uses a graduated approach:

- **Education and guidance** for first-time or low-risk non-compliance.
- **Compliance verification** through inspections and sampling.
- **Administrative monetary penalties** of up to $25,000 per violation for designated violations, providing a faster sanction than prosecution.
- **Recall and other orders** to remove dangerous products from the market.
- **Prosecution** for serious offences, including failure to comply with orders, with fines and imprisonment available.

Import surveillance is a priority: products stopped at the border never reach consumers, and Health Canada publishes information on import refusals to deter non-compliant shipments.

## Import surveillance in practice

Health Canada's work with the Canada Border Services Agency targets non-compliant consumer products before they reach the market:

- **Targeting**: shipments are selected based on risk indicators, including product type, origin, importer history and intelligence from incident reports and foreign regulators.
- **Examination**: selected shipments are held for document review and product examination or testing. Importers must produce evidence of compliance with applicable regulations.
- **Outcomes**: compliant shipments are released; non-compliant shipments can be refused entry, ordered re-exported or destroyed, or released subject to corrective conditions.
- **Importer consequences**: repeated non-compliance leads to increased examination rates and enforcement action against the importer.

For importers, the lesson is to treat every shipment as potentially examined: maintain compliance files per product, ensure labelling is correct before shipping, and designate a contact who can respond to border queries quickly.

## Guidance documents and how to use them

Health Canada publishes extensive guidance: regulatory summaries, guidance on incident reporting, cosmetic notification guides, and product-specific interpretive documents. These are not law, but they reveal how Health Canada interprets the law and what inspectors look for. Compliance programs should:

1. Map each applicable regulation to its guidance documents.
2. Treat guidance positions as the default compliance standard unless there is a reasoned basis to differ.
3. Track guidance updates, since they often precede regulatory amendments.
4. Document where the business follows guidance and where it takes a different, justified approach.

