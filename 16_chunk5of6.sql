- Importer records: verification steps, declaration copies.
- Corrective action records: complaints, investigations, withdrawals and recalls.

## Enforcement

Market surveillance is carried out by local trading standards authorities coordinated by OPSS, with border checks on imports. Enforcement follows the powers in each statutory instrument: documentation requests, inspections, corrective action orders, withdrawal and recall, and prosecution with fines and imprisonment for offences. The product safety database supports business notifications and authority coordination.

## How the current position evolved

Understanding the timeline helps businesses interpret older advice and documentation:

- **31 December 2020**: end of the Brexit transition period; EU product law as it stood became retained UK law.
- **2021-2022**: government announced, then extended, deadlines for UKCA marking to replace CE marking, creating repeated replanning for industry.
- **1 August 2023**: government announced indefinite recognition of CE marking for 18 sets of regulations, removing the hard cutover for covered sectors.
- **2024**: the Product Regulation and Metrology Bill was introduced to enable faster future updates to product law.
- **Ongoing**: sector guidance is updated as the Bill progresses and as designated standards lists evolve.

Documentation and advice predating August 2023 may still assume a CE-to-UKCA cutover that no longer applies in covered sectors; always check the current guidance.

## Sector guidance map

The central guidance links to product-specific GOV.UK pages that businesses must consult for their sectors. The main regulated areas include:

- Electrical equipment, toys, machinery, radio equipment and telecommunications terminal equipment.
- Personal protective equipment, pressure equipment, gas appliances.
- Medical devices (with a distinct regulatory framework and its own transition).
- Construction products, civil explosives, recreational craft.
- Ecodesign and energy labelling (separate but related regimes).

Each sector page sets out the applicable UK regulations, the conformity assessment routes, the marking position (UKCA required vs CE recognised), and any approved body requirements. The central guidance gives the framework; the sector pages give the answers.

## Staying current

1. Re-check the CE recognition position for each product sector periodically; sector guidance is updated as policy develops.
2. Track the Product Regulation and Metrology Bill and secondary legislation, which may change marking, assessment and enforcement rules.
3. Keep designated standards lists current for presumption of conformity.
4. For goods also sold in Northern Ireland or the EU, maintain parallel compliance (UKNI/CE as applicable) rather than assuming GB compliance transfers.
5. Treat the guidance as a living document: bookmark the sector pages for your products and review them on a schedule, since recognition positions and designated standards change without direct notice to businesses. Assign ownership for regulatory monitoring explicitly within the business.

## Frequently asked questions

**Do I need UKCA marking if my product already has CE marking?**
In many sectors, no: CE marking is recognised indefinitely for 18 sets of regulations. But recognition is sector-specific, and UK importer duties still apply. Check the sector guidance for your product.

**What is a UK approved body?**
A conformity assessment body designated by the UK government to carry out third-party assessment for UKCA marking. Only UK approved bodies (not EU notified bodies) can support UKCA certification.

**I am a non-UK manufacturer. What do I need in the UK?**
A UK-based importer or authorised representative meeting UK-specific requirements. The authorised representative must have a written mandate covering the UK duties; EU authorised representative arrangements do not automatically transfer.

**Where is the authoritative law?**
The statutory instruments on legislation.gov.uk. The GOV.UK guidance explains them but does not replace them.

**Does this guidance cover Northern Ireland?**
No. Northern Ireland follows EU product rules under the Windsor Framework. The guidance signposts the separate NI rules, including CE/UKNI marking.

