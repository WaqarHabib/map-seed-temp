## Scope and who must comply

The regulations apply to **electrical equipment** designed for use with a voltage rating between 50 and 1,000 volts for alternating current and between 75 and 1,500 volts for direct current, placed on the GB market. This covers the great majority of mains-powered and many battery-powered consumer and commercial electrical products.

Exclusions include equipment for explosive atmospheres, radiology and medical purposes, parts for goods and passenger lifts, electricity meters, plugs and socket outlets for domestic use, electric fence controllers, and specialised equipment for ships, aircraft and railways (covered by other regimes).

Duties fall on **manufacturers**, **authorised representatives** (where appointed), **importers** and **distributors**, with the manufacturer carrying primary responsibility for design, conformity assessment and marking. An importer or distributor placing equipment on the market under their own name or trademark, or modifying equipment in a way affecting compliance, assumes manufacturer duties.

## Key obligations

**Essential safety requirements.** Schedule 1 sets the principal safety objectives: equipment must be designed and manufactured to ensure protection against hazards from the equipment itself and from external influences, including:

- Protection against electric shock (direct and indirect contact).
- Protection against dangerous temperatures, arcs and radiation.
- Protection against non-electrical dangers (mechanical, chemical) revealed by experience.
- Adequate insulation for foreseeable conditions.
- Withstand of mechanical stresses and environmental influences.
- Marking of safety information, including rated voltages and safe use instructions.

**Conformity assessment.** The manufacturer must carry out **internal production control** (the Module A procedure in Schedule 3): assessing the design and manufacture against the safety objectives, typically by applying **designated standards** (which give presumption of conformity), and drawing up technical documentation.

**UKCA marking and declaration.** Before placing equipment on the market, the manufacturer must draw up the **UK Declaration of Conformity** and affix the **UKCA marking** visibly, legibly and indelibly. (CE marking remains recognised for this sector following the government's indefinite CE recognition announcement, but the underlying duties are those of the UK regulations.)

**Traceability.** Equipment must bear a type, batch or serial number (or other identifier) and the manufacturer's name, registered trade name or trademark and a contact address. Importers must add their own name and address. Instructions and safety information must be in English and clear.

**Ongoing duties.** Manufacturers must ensure series production remains compliant, keep the technical documentation and declaration for 10 years, sample-test where appropriate, investigate complaints, and take corrective action (withdrawal, recall) for non-compliant equipment, informing the enforcement authorities where equipment presents a risk.

## Documentation and labelling

- **Technical documentation**: design and manufacturing descriptions, risk assessment, test reports, list of designated standards applied, and evidence supporting the safety assessment. Retained for 10 years after the last equipment is placed on the market.
- **UK Declaration of Conformity**: identifying the equipment, the manufacturer, the legislation applied and the standards used, signed and dated.
- **UKCA marking** on the equipment (or packaging/documents where the nature of the equipment requires).
- **Traceability marking**: identifier, manufacturer and importer details.
- **Instructions and safety information** in English.

## Enforcement and penalties

- **Enforcement authorities**: local weights and measures authorities (trading standards) in Great Britain, with OPSS coordinating and handling national issues.
- **Powers**: inspectors can require documentation, enter premises, inspect and test equipment, and require corrective measures including withdrawal and recall.
- **Offences**: placing non-compliant equipment on the market, misusing the UKCA marking, failing to draw up or keep the declaration and technical documentation, and obstructing enforcement are offences.
- **Penalties**: on summary conviction, imprisonment of up to 3 months or a fine; on indictment, imprisonment of up to 2 years or a fine. Penalties must be effective, proportionate and dissuasive.

## Designated standards and presumption of conformity

Electrical equipment manufactured in conformity with **designated standards** (published by the Secretary of State, largely adopting the former harmonised EN standards) is presumed to comply with the safety objectives they cover. In practice, compliance programmes are built around the applicable designated standards (for example, the EN 60335 series for household appliances, EN 62368-1 for audio/video and IT equipment), with testing by competent laboratories and the standards list checked for currency.

## Common compliance pitfalls

Enforcement experience points to recurring failures businesses should design against:

- **Legacy CE documentation**: technical files and declarations still referencing EU directives rather than the UK regulations and designated standards. Post-transition files should cite SI 2016/1101 and designated standards.
- **Missing importer details**: non-UK manufacturers' products reaching GB without the UK importer's name and address on the product, packaging or documents.
- **Instructions not in English or incomplete**: safety information that is translated poorly, omits warnings, or is only available online where the regulations expect it with the product.
- **No designated standards cited**: technical files that describe testing without mapping results to the safety objectives or the designated standards applied.
- **Uncontrolled design changes**: component substitutions or supplier changes that are not re-assessed against the safety objectives, particularly for insulation, creepage and clearance distances.

## Designated standards in practice

The designated standards system works as follows:

- The Secretary of State publishes lists of designated standards; conformity with them gives presumption of conformity with the corresponding safety objectives.
- Most designated standards are adoptions of European EN standards (for example, EN 60335-1 for household appliance safety, EN 62368-1 for ICT and audio/video equipment), so existing test data to the EN versions generally remains usable.
- Where no designated standard covers a hazard, the manufacturer must demonstrate compliance with the safety objectives directly, with the technical file explaining the assessment method.
- Standards are updated periodically; the designation list specifies which edition is current, and transition periods apply when editions change.

## The importer's verification duty

Importers carry a specific, enforceable verification burden that is often under-documented:

1. Before placing equipment on the market, verify the manufacturer has carried out the conformity assessment, drawn up the technical documentation and affixed the UKCA marking (or CE marking where recognised).
2. Ensure the equipment bears the required traceability information and is accompanied by instructions and safety information in English.
3. Add your own name, registered trade name or trademark and contact address to the equipment, its packaging or accompanying documents.
4. Keep a copy of the UK Declaration of Conformity and ensure the technical documentation can be made available to enforcement authorities on request.
5. Where you have reason to believe equipment is non-compliant, do not place it on the market; where it presents a risk, take corrective action and inform the authorities.

Distributors have a parallel duty of care: verifying marking, documentation and instructions before making equipment available, and cooperating on corrective action.

## Staying current

1. Check the designated standards lists for your product types; presumption of conformity depends on current designations.
2. Confirm the UKCA/CE position for your sector, since recognition arrangements are sector-specific.
3. Keep technical files aligned to the UK regulations (UK declaration, designated standards references), not legacy EU documentation.
4. Monitor OPSS guidance and enforcement priorities for electrical equipment.

## Frequently asked questions

**What voltage range is covered?**
50 to 1,000 V AC and 75 to 1,500 V DC. Equipment outside these ranges (for example, low-voltage battery devices) falls under other regimes such as the General Product Safety Regulations 2005 or sector-specific rules.

**Do I need an approved body?**
No. The regulations use internal production control (Module A, self-declaration). No third-party certification is required, though testing by a competent laboratory is the normal way to demonstrate compliance with designated standards.

**Is CE marking accepted instead of UKCA?**
For electrical equipment, CE marking remains recognised following the government's indefinite recognition announcement. However, the applicable law is the UK regulations, and documentation should reflect that. Check current sector guidance to confirm.

**Who enforces the regulations?**
Local trading standards (weights and measures authorities) in Great Britain, coordinated nationally by OPSS.

**What are the penalties?**
Criminal offences with penalties of up to 3 months' imprisonment or a fine on summary conviction, and up to 2 years' imprisonment or a fine on indictment.

