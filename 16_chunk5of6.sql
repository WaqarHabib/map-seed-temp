## The UK product safety landscape after EU exit

Since the end of the Brexit transition period, Great Britain has operated its own product safety regime. EU directives were initially transposed into UK law and later converted into **assimilated law**, with UK statutory instruments replacing EU references (CE marking becoming UKCA marking, EU declarations becoming UK declarations of conformity, notified bodies becoming UK approved bodies, harmonised standards becoming designated standards).

Key structural points:

- **Great Britain vs Northern Ireland**: product rules described on GOV.UK generally apply to Great Britain (England, Scotland, Wales). Northern Ireland continues to follow EU product rules under the Windsor Framework, with the UKNI marking used alongside CE marking in specific circumstances.
- **UKCA marking**: the UK conformity mark for most manufactured goods placed on the GB market. On 1 August 2023 the government announced it would **recognise CE marking indefinitely** for 18 sets of regulations (beyond the previous December 2024 deadline), so businesses can in many areas use either UKCA or CE marking. The exact position varies by product sector, so the sector-specific guidance must be checked.
- **Designated standards**: UK standards designated by the Secretary of State give presumption of conformity, replacing the EU harmonised standards mechanism.
- **OPSS**: the national regulator for product safety, providing guidance, coordinating market surveillance with local authorities, running the product safety database, and taking national enforcement action.

## What GOV.UK provides

GOV.UK hosts the operational core of the regime:

- **Sector guidance**: placing manufactured goods on the GB market, UKCA marking rules, and product-specific guidance (electrical equipment, toys, machinery, radio equipment, PPE and others).
- **Product safety alerts, recalls and reports**: the public database of unsafe products, with email alerts.
- **Business guidance**: how to comply, how to report unsafe products, and how to conduct recalls.
- **Legislation**: the authoritative texts on legislation.gov.uk, linked from guidance.

Businesses should treat GOV.UK guidance as the starting point and legislation.gov.uk as the authority, since guidance summarises but does not replace the statutory instruments.

## Key obligations across the regime

While each product regulation has its specifics, the common pattern (derived from the former EU NLF structure) is:

1. **Identify the applicable regulations** for the product (often more than one).
2. **Meet the essential safety requirements** in each regulation's schedules.
3. **Carry out conformity assessment**: usually internal production control (Module A, self-declaration) against designated standards; approved body involvement for higher-risk categories.
4. **Draw up the UK Declaration of Conformity** and affix the UKCA marking (or CE marking where recognised).
5. **Ensure traceability**: type/batch/serial identification and manufacturer/importer name and address.
6. **Provide instructions and safety information** in English.
7. **Keep technical documentation** (typically 10 years) and cooperate with market surveillance.
8. **Take corrective action** (withdrawal, recall) for unsafe products and notify authorities.

The **General Product Safety Regulations 2005** provide the safety net for consumer products not covered by specific regulations, requiring that only safe products are placed on the market and imposing traceability and notification duties.

## Market surveillance and enforcement

- **Local authorities** (trading standards) enforce product safety at the local level, with OPSS coordinating nationally and handling the most serious cases.
- **Border controls**: the Border Force and market surveillance authorities check imported products.
- **Product Safety Database**: the system for business notifications and authority coordination.
- **Recalls**: businesses must notify and conduct recalls of unsafe products; OPSS publishes alerts and can publicise enforcement action.
- **Penalties**: set by each statutory instrument and typically include fines and imprisonment; the general regime requires penalties to be effective, proportionate and dissuasive.

The Product Regulation and Metrology Bill, introduced in 2024, is intended to give ministers powers to update product law more responsively, including alignment or divergence decisions. Businesses should track its progress and any secondary legislation made under it.

## Product safety alerts, recalls and the business notification duty

The UK's public product safety system centres on GOV.UK's alerts and recalls service:

- **Business notifications**: businesses that place unsafe products on the market must notify the authorities through the Product Safety Database, providing product identification, the nature of the risk, distribution details and proposed corrective action.
- **Public alerts**: OPSS and local authorities publish alerts, recalls and safety reports on GOV.UK, searchable by product category, with email subscription options.
- **Corrective action**: businesses are expected to implement effective corrective action (repair, replacement, refund, withdrawal) and to monitor its effectiveness. Poorly executed recalls draw enforcement attention.
- **Cross-border alerts**: the UK no longer participates in the EU Safety Gate system; it operates its own alerting, while cooperating internationally on product safety intelligence.

For businesses, the notification duty means incident response procedures must include a UK reporting path with clear internal ownership, not just EU or US processes.

## The Product Regulation and Metrology Bill

Introduced in 2024, the Product Regulation and Metrology Bill is designed to give ministers powers to update product law by secondary legislation, covering product safety, environmental and metrology requirements. Its significance for businesses:

- It would allow faster updates to product regulations without primary legislation, meaning the regulatory landscape could change more quickly than in the past.
- It provides for potential alignment with, or divergence from, EU product law on a sector-by-sector basis.
- Businesses should track the Bill's parliamentary progress and, more importantly, the secondary legislation made under it once enacted, since that is where concrete duties will appear.

