2. **Decide UKCA vs CE**: confirm for each product sector whether CE marking remains recognised or UKCA marking is required, and whether an approved body is needed.
3. **Use designated standards**: check the current designated standards lists for presumption of conformity.
4. **Prepare UK declarations**: ensure declarations of conformity reference UK legislation and designated standards, not EU directives.
5. **Appoint UK responsible persons**: non-UK manufacturers need UK-based importers or authorised representatives; authorised representative arrangements must meet UK-specific requirements.
6. **Monitor OPSS**: guidance updates, alerts and enforcement priorities signal where attention is focused.

## Staying current

1. Check GOV.UK sector guidance regularly; it is updated as policy evolves (for example, the CE recognition announcement changed planning assumptions across sectors).
2. Track the Product Regulation and Metrology Bill and any regulations made under it.
3. Monitor the product safety alerts database for your categories.
4. For Northern Ireland trade, follow the Windsor Framework product rules separately; GB guidance does not cover NI.

