**Short answer:** GOV.UK is the UK government's official source for product safety law and guidance. The UK product safety regime is administered by the Office for Product Safety and Standards (OPSS), part of the Department for Business and Trade, and built on product-specific regulations (many retained from EU law and amended for Great Britain), the General Product Safety Regulations 2005, market surveillance, and a national recalls and alerts system. It affects any business placing consumer or commercial products on the UK market.

