## Scope and who must comply

The CPSA covers **consumer products**: articles produced or distributed for sale to consumers for use in or around a household, school or recreation. Excluded products include tobacco, motor vehicles, pesticides, firearms, aircraft, boats, food, drugs, cosmetics and medical devices, which are regulated by other agencies.

The CPSIA added its toughest requirements for **children's products**: products designed or intended primarily for children 12 years of age or younger. Determining whether a product is a children's product follows CPSC guidance considering the manufacturer's stated intent, packaging and marketing, and consumer perception.

The statutes bind manufacturers (including importers, who are treated as manufacturers for imported products), private labelers, distributors and retailers. Importers carry particular weight because CPSC enforces heavily at the border in cooperation with U.S. Customs and Border Protection (CBP).

## Key obligations

**Lead limits.** The CPSIA set strict lead limits for children's products: 90 ppm for lead in paint and surface coatings (16 CFR 1303) and 100 ppm total lead content in accessible substrate materials of children's products. These are among the strictest lead limits in the world and apply regardless of product category.

**Phthalates.** 16 CFR 1307 prohibits more than 0.1% of eight specified phthalates in children's toys and child care articles. The list and scope have been updated since the CPSIA's original six-phthalate provision, so the current CFR text is the reference.

**Third-party testing and certification.** Children's products subject to a CPSC rule must be tested by a **CPSC-accepted laboratory** (listed on the CPSC website), and the manufacturer or importer must issue a **Children's Product Certificate (CPC)** certifying compliance with each applicable rule, based on the third-party test results. Testing must follow the requirements of 16 CFR 1107, including periodic testing and material-change retesting.

**General Certificate of Conformity (GCC).** Non-children's products subject to CPSC rules require a GCC based on a reasonable testing program (first-party testing is generally acceptable), rather than mandatory third-party testing.

**Tracking labels.** Children's products must bear distinguishing permanent marks enabling the manufacturer, production location and date, and other traceability information (tracking labels), to support recalls.

**Durable infant and toddler products.** Subject to product-specific CPSC standards (16 CFR parts 1215-1236 and others), registration cards, and additional labelling. Standards are routinely updated, and each product type (cribs, strollers, high chairs and others) has its own rule.

**Prohibited acts and reporting.** Section 15(b) of the CPSA requires firms to report to CPSC when they obtain knowledge of a product defect that could create a substantial product hazard or an unreasonable risk of serious injury or death. Failure to report is itself a violation and a frequent basis for civil penalties.

## Conformity process

1. **Classify the product**: is it a children's product (12 and under) or a general-use product? This determines the entire compliance path.
2. **Identify applicable rules**: mandatory standards, bans and limits in 16 CFR for the product type (lead, phthalates, flammability, small parts, specific product standards).
3. **Test**: children's products at a CPSC-accepted laboratory; general-use products under a reasonable testing program.
4. **Certify**: issue the CPC (children's) or GCC (general-use), with the certificate accompanying the product or shipment and furnished to authorities and buyers on request.
5. **Label**: apply tracking labels (children's products) and any required warnings or labelling.
6. **Import compliance**: for regulated imported products, electronically file certificate data with CBP at entry under the eFiling rule (16 CFR Part 1110), effective 8 July 2026 for most imports.
7. **Monitor**: maintain a Section 15(b) reporting procedure and recall readiness.

## Documentation and labelling

- CPC or GCC for each product, identifying the product, the certifier, the test lab (for CPCs), the date and place of manufacture and testing, and each rule certified.
- Test reports from CPSC-accepted laboratories (children's products) or reasonable testing program records (general-use).
- Tracking labels on children's products and packaging.
- Records supporting the children's product determination.
- Section 15(b) evaluation records and reports filed with CPSC.

Certificates must be furnished to CBP, CPSC and buyers; the eFiling rule moves this into electronic filing at the time of entry.

## Enforcement and penalties

- **Civil penalties**: the CPSA authorises civil penalties of up to $100,000 per violation as adjusted for inflation (currently over $120,000), with aggregate caps per related series of violations in the tens of millions. Failure to report under Section 15(b) routinely draws multi-million-dollar penalties.
- **Criminal penalties**: knowing and willful violations can lead to fines and imprisonment.
- **Recalls**: CPSC negotiates corrective action plans, including recalls; firms must implement them once agreed, and CPSC publicises recalls.
- **Import enforcement**: CBP, working with CPSC's import surveillance program, detains and refuses violative shipments at ports of entry.
- **State enforcement**: state attorneys general can enforce certain CPSIA provisions.

## Civil penalty practice

CPSC civil penalties follow recognisable patterns that compliance programs should internalise:

- **Late reporting dominates**: the largest penalties typically involve failure to report under Section 15(b) promptly, not the underlying defect alone. CPSC measures timeliness from when the firm obtained reportable knowledge, and its "should have known" standard is demanding.
- **Penalty factors**: CPSC considers the severity of the risk, the number of products, the firm's cooperation, and its compliance history. Agreed corrective action plans often accompany penalty settlements.
- **Compliance program credit**: firms with documented, working compliance programs (product safety management, reporting procedures, testing protocols) fare better in negotiations than firms that improvise after an incident.

The practical lesson is that the reporting procedure matters as much as product design: a defect handled through prompt reporting and an effective recall costs far less than the same defect discovered through CPSC investigation.

## Staying current

1. Track 16 CFR rulemakings for your product category; CPSC regularly issues or updates mandatory standards.
2. Verify your test lab's CPSC acceptance status before each testing cycle; acceptance can change.
3. Prepare for eFiling: certificate data must be filed electronically at import from July 2026, with no de minimis exception.
4. Maintain a written Section 15(b) reporting procedure with clear internal escalation, since late reporting is a standalone violation.

## Frequently asked questions

**What is the difference between a CPC and a GCC?**
A Children's Product Certificate (CPC) is required for children's products subject to CPSC rules and must be based on third-party testing by a CPSC-accepted laboratory. A General Certificate of Conformity (GCC) covers non-children's products subject to CPSC rules and may be based on the manufacturer's reasonable testing program.

**Do I need third-party testing for adult products?**
Generally no. Mandatory third-party testing applies to children's products. General-use products require certification based on a reasonable testing program, which is typically first-party or supplier testing.

**What are the lead limits?**
90 ppm for lead in paint and surface coatings on children's products and furniture, and 100 ppm total lead content in accessible components of children's products. These limits come from the CPSIA and its implementing rules.

**I import products made abroad. Who is responsible?**
The importer is treated as the manufacturer under the CPSA for imported products. You must ensure testing, certification and labelling, and you face enforcement at the border.

**What triggers a Section 15(b) report?**
Information reasonably supporting the conclusion that a product contains a defect that could create a substantial product hazard, or creates an unreasonable risk of serious injury or death. When in doubt, firms typically report, since failure to report draws penalties independently of the underlying defect.

**How do I determine if my product is a "children's product"?**
CPSC guidance looks at the manufacturer's stated intent (marketing, labelling, advertising), the product's packaging and display, and whether consumers commonly perceive it as intended for children 12 or younger. Age grading, decorative themes and play value all factor in. Document your determination carefully and revisit it if marketing changes.

