## Scope and who must comply

The rule applies to **importers of record** of consumer products subject to a CPSC rule, ban, standard or regulation requiring certification: children's products requiring a Children's Product Certificate (CPC) and general-use products requiring a General Certificate of Conformity (GCC). If the product requires a certificate under the CPSA or CPSIA, its certificate data must be filed electronically at entry.

There is **no de minimis exception**: low-value shipments of regulated products are covered. Importers using foreign trade zones have a later compliance date (8 January 2027 for withdrawals) but are not exempt. The rule also provides for **disclaimers**: where a product is not subject to CPSC certification requirements, the filer transmits a disclaimer message (with the appropriate disclaimer code) rather than certificate data.

Customs brokers filing on behalf of importers must be able to transmit the CPSC message set, and importers remain responsible for the accuracy of the filed data.

## Key obligations

**Electronic filing of certificate data.** At the time of entry, the importer (or broker) files structured certificate data through the CPSC PGA message set in ACE. The filing references the certificate and its key data elements rather than attaching a PDF: product identification, the certificate reference, the certifier, and the regulatory citations to which the product is certified.

**Product Registry.** CPSC operates an online **Product Registry** where importers create certificate records and generate references used in the ACE filing. Businesses should establish registry accounts, define who creates and approves certificate records, and integrate the registry into their import workflow well before the compliance date.

**Data accuracy.** Filed data must match the underlying certificate (CPC or GCC) and the test records supporting it. Inaccuracies can trigger CBP holds, CPSC examination and penalties, so the filing process must be tied to the actual testing and certification workflow, not treated as a paperwork afterthought.

**Disclaimers.** For products not subject to CPSC certification, filers use the disclaimer message set with the correct code. Using a disclaimer for a regulated product, or filing certificate data for an uncertified product, creates compliance risk in both directions.

**Recordkeeping.** Importers must maintain the certificates and supporting test records underlying each filing and produce them to CPSC or CBP on request.

## Implementation process

1. **Determine coverage**: map your imported products against CPSC certification requirements (CPC vs GCC vs disclaimer).
2. **Set up the Product Registry**: create accounts, assign roles, and establish procedures for creating certificate records.
3. **Align testing and certification**: ensure every regulated product has a current, accurate certificate before it ships, since the filing references it.
4. **Broker readiness**: confirm your customs broker can transmit the CPSC PGA message set in ACE and has tested the filing flow.
5. **Build the data pipeline**: connect product, testing and certificate data so the correct reference is filed for each entry line.
6. **Test before the deadline**: use CPSC's testing resources and pilot filings to validate the workflow before 8 July 2026.
7. **FTZ planning**: if you use Foreign Trade Zones, plan for the 8 January 2027 withdrawal compliance date.

## Documentation

- CPCs and GCCs for all regulated imported products, with supporting test reports.
- Product Registry records and certificate references.
- ACE filing records per entry.
- Broker instructions and filing confirmations.
- Disclaimer justifications for products filed as disclaimed.

## Enforcement and penalties

- CBP can hold, examine and refuse entry to shipments with missing, inaccurate or mismatched certificate data.
- CPSC can pursue civil penalties for certification and filing violations under the CPSA's penalty provisions.
- Systematic filing failures can lead to increased examinations, import alerts and loss of trusted-trader benefits.
- Because there is no de minimis exception, small-parcel and e-commerce import flows need the same filing discipline as container shipments.

## The filing data model

The eFiling message set is structured around the certificate, not the shipment. Understanding this shapes how businesses organise their data:

- **Certificate-centric**: each filing references a certificate record (created in the Product Registry) that identifies the product, the certifier, the testing laboratory (for CPCs) and the regulatory citations. One certificate can cover multiple entries of the same product.
- **Product identification**: the filing must identify the product precisely enough for CPSC to match it to the certificate and to target examinations. Consistent product identifiers between commercial invoices, certificates and filings reduce holds.
- **Regulatory citations**: the filing cites the specific CPSC rules, bans and standards to which the product is certified, so CPSC systems can validate coverage.
- **Disclaimer codes**: for non-regulated products, the disclaimer code communicates why no certificate is required. Filers should document the basis for each disclaimer used, since misuse is enforceable.

Businesses should map these elements to their product master data now: the filing is only as reliable as the product-to-certificate linkage behind it.

## Broker, software and systems readiness

Most importers will file through their customs broker or a software provider, which creates a readiness chain:

1. **Broker capability**: confirm your broker supports the CPSC PGA message set in ACE and has completed CPSC's testing. Brokers serving many importers face capacity constraints approaching the deadline.
2. **Data handoff**: define how certificate references flow from your compliance team to the broker for each shipment. Ad hoc emails do not scale; integrate the reference into shipping documentation or EDI.
3. **Software**: if you self-file or use a trade compliance platform, verify the platform's CPSC message set support and test end to end.
4. **Error handling**: establish procedures for filing rejections, CBP holds and data mismatches, with named contacts at the broker and internally.

Starting this work a full business cycle before the deadline leaves room to fix data quality problems, which are the most common cause of filing failures in CPSC's pilot phases.

## Staying current

1. Follow CPSC's eFiling Document Library and mailing list for implementation guidance, message set updates and testing windows.
2. Confirm your broker's ACE readiness early; broker capacity constraints near the deadline are a foreseeable bottleneck.
3. Treat the certificate as the filing's foundation: a filing is only as good as the testing and certification behind it.
4. Monitor CPSC announcements for any adjustments to dates, data elements or disclaimer codes.

## Frequently asked questions

**When does eFiling become mandatory?**
8 July 2026 for most imports. Goods withdrawn from Foreign Trade Zones must comply from 8 January 2027. Voluntary filing and testing are available before those dates.

**Is there a minimum shipment value?**
No. The rule has no de minimis exception; regulated products in low-value shipments must still have their certificate data filed.

**What if my product is not subject to CPSC certification?**
File a disclaimer using the CPSC disclaimer message set with the appropriate code, rather than certificate data. The product must genuinely fall outside CPSC certification requirements.

**Who files: the importer or the broker?**
The importer of record is responsible for compliance; in practice the customs broker typically transmits the filing in ACE on the importer's behalf. The importer remains liable for accuracy.

**Where do I create the certificate reference?**
In CPSC's Product Registry, the online system for creating certificate records referenced by ACE filings. CPSC provides registration guidance and FAQs on the eFiling page.

**Does eFiling replace the paper certificate?**
The underlying certificate (CPC or GCC) is still required; eFiling changes how its data is communicated to the government at entry, from paper accompanying shipments to structured electronic filing.

**What happens if my filing is rejected in ACE?**
Rejections must be resolved before the goods can be released. Common causes are mismatched certificate references, missing data elements and broker transmission errors. Your error-handling procedure should identify whether the problem is data (fix the certificate reference) or transmission (work with the broker), and refile promptly.

