**Short answer:** The CPSC eFiling rule (16 CFR Part 1110, final rule published 8 January 2025) requires importers of regulated consumer products to electronically file certificate-of-compliance data with U.S. Customs and Border Protection at the time of entry, using the CPSC Partner Government Agency message set in the Automated Commercial Environment (ACE). It takes effect 8 July 2026 for most imports and 8 January 2027 for goods withdrawn from Foreign Trade Zones, with no de minimis exception. It affects every importer of consumer products subject to CPSC rules.

