**Short answer:** The Consumer Product Safety Act of 1972 (CPSA) created the U.S. Consumer Product Safety Commission (CPSC) and gave it authority over consumer product safety. The Consumer Product Safety Improvement Act of 2008 (CPSIA) dramatically strengthened the regime after high-profile recalls: it set strict lead and phthalate limits, mandated third-party testing of children's products by CPSC-accepted laboratories, required Children's Product Certificates, and tightened import controls. Together they govern the safety of most consumer products sold in the United States.

