A labelling architecture designed for the EU, with a translation matrix keyed to member states, adapts more easily to additional markets than one designed for a single language. Build the matrix once and extend it.

## How should sellers manage label artwork control?

Labelling errors are a leading cause of preventable non-compliance. A document control process for labels should include:

* Version control linking each label revision to the product configuration and the technical file
* A checklist of required elements per market, signed off before artwork release
* Translation verification by qualified linguists, not machine translation alone, for safety-critical warnings
* Proof review against the regulatory checklist, not just visual design review
* Retention of superseded label versions with the technical file for the retention period

Where products are sold through distributors who apply local labels, the agreement should specify who is responsible for label compliance and require approval of any locally produced artwork.

