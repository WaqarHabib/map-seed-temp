In the US, sector-specific traceability rules continue to expand. The FDA Unique Device Identification system for medical devices illustrates the direction: standardised identifiers, database registration, and carrier requirements on labels.

For consumer products, the practical step is to design labels with a scannable identifier linked to a product information page that can be extended over time. A QR code resolving to a page containing the current compliance information is adaptable to future requirements in both markets.

## What special rules apply to children products labelling?

Children products face the strictest labelling in both markets, and the requirements deserve separate attention.

In the US, the tracking label rule requires distinguishing marks on the product and packaging enabling the manufacturer and private labeller, the production location and date, and other cohort information. Small-batch manufacturers have modified requirements but are not exempt.

In the EU, childcare articles and toys fall under sector-specific legislation with detailed labelling: age warnings with prescribed formats, chemical information, and traceability. The GPSR general requirements add the manufacturer and EU operator details.

For sellers of children products in both markets, the label must satisfy the stricter of the overlapping requirements for each element. Maintain a dedicated labelling checklist for children products rather than adapting the general consumer product checklist.

## How should multilingual safety warnings be validated?

Safety warnings in multiple languages carry legal weight. A mistranslated warning is worse than a missing one if it creates a false impression of safety.

The validation process should:

* Use translators qualified in technical or legal translation, not general consumer translation
* Back-translate safety-critical warnings to verify the meaning survived translation
* Test warnings with native speakers unfamiliar with the product to confirm comprehension
* Review translations when the source warning changes; version control must link source and translation revisions

Machine translation may assist with drafts but should not be the final step for safety information. The cost of professional translation is small relative to the liability exposure of an incorrect warning.

