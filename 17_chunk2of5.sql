## How do authorities choose between penalties and corrective action?

Enforcement is not a single track. Authorities choose from a graduated toolkit, and understanding the logic helps sellers respond appropriately when contacted.

The typical escalation sequence:

1. **Information request.** The authority asks for the technical documentation or Declaration of Conformity. This is routine surveillance, not an accusation.
2. **Corrective action request.** The authority identifies a non-compliance and sets a deadline for correction, such as adding missing labelling or providing translations.
3. **Restriction.** If the risk warrants it, the authority orders withdrawal from the market or prohibits further supply while the issue is addressed.
4. **Recall.** For products already with consumers that present a risk, the authority orders or agrees a consumer recall.
5. **Penalty.** Financial penalties follow, scaled to the seriousness, the cooperation shown, and the harm caused or risked.

Cooperation at stage one and two significantly affects the outcome at stage five. Authorities distinguish between sellers who correct promptly and those who obstruct. The file you produce in response to the first request shapes everything that follows.

