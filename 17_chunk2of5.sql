* Map the fixed costs: technical file preparation, testing, translations, label design
* Map the recurring costs: surveillance of regulatory changes, documentation updates, authority cooperation
* Compare against the cost of a single enforcement event in your category, using public recall and penalty data as reference points
* Present the comparison to decision-makers in commercial terms, not legal abstractions

Compliance is cheapest when built into product development. Retrofitting documentation for a product already shipping costs multiples of doing it during design.

## How do penalty levels compare across major markets?

The absolute penalty figures differ significantly, but the comparison that matters for business decisions is the penalty relative to the commercial stakes and the probability of enforcement.

The EU GPSR framework sets maximum fines at levels that scale with the seriousness of the infringement, with member states implementing the details. Some member states set maxima in the millions of euros for serious safety violations. The Market Surveillance Regulation adds the possibility of penalties for obstructing authorities.

