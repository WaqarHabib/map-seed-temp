'## Short answer

An EU technical file must document the product design, the risk assessment, the applicable legislation and harmonised standards, test reports and calculations, and the conformity assessment performed. It must be retained for ten years after the last unit is placed on the market and produced to market surveillance authorities on request.

## What is the technical file?

The technical file, sometimes called technical documentation, is the documented evidence that a product meets the applicable EU requirements. It is the manufacturer responsibility and the first thing a market surveillance authority asks to see.

The concept comes from the New Legislative Framework (Decision No 768/2008/EC), which provides model provisions used across harmonisation directives. Each directive contains an annex describing the technical documentation for its conformity assessment modules, but the core structure is consistent.

The file must be drawn up before the product is placed on the market. It is not a marketing document. It is an engineering record.

## What must the technical file contain?

The typical contents, drawn from the NLF model provisions, are:

1. **Product description.** A general description of the product, including its intended use, variants, and models covered.

2. **Design documentation.** Conceptual design and manufacturing drawings, descriptions of components, and explanations necessary to understand those drawings.

3. **Applicable legislation.** A list of the EU harmonisation laws the product complies with.

4. **Standards applied.** A list of harmonised standards applied in full or in part, with references. Where harmonised standards have not been applied, a description of the solutions adopted to meet the essential requirements.

5. **Risk assessment.** The documented analysis of hazards and the measures taken to address them, following the priority order: inherently safe design, protective measures, information for users.

6. **Test reports.** Results of design calculations, examinations carried out, and test reports from internal or external laboratories.

7. **Conformity assessment records.** Evidence of the assessment performed, including notified body certificates or decisions where the module requires involvement.

8. **EU Declaration of Conformity.** A copy of the signed declaration.

9. **Labelling and instructions.** Copies of the marking, labelling, and instructions as supplied with the product.

## How should the file be structured?

There is no mandated file format, but authorities expect a coherent, navigable record. A practical structure:

| Section | Contents |
|---|---|
| A. Product identification | Description, models, variants, photos |
| B. Legal basis | Applicable directives, standards list |
| C. Risk assessment | Hazard analysis, mitigation measures |
| D. Design evidence | Drawings, schematics, component lists |
| E. Test evidence | Test reports, calculations, lab credentials |
| F. Assessment records | Module followed, notified body documents if any |
| G. Market documents | Declaration of Conformity, labels, instructions |

Each section should be dated and version-controlled. When the product changes, the file must be updated and the conformity reassessed.

## Who keeps the file and for how long?

The manufacturer draws up and keeps the technical documentation. Importers must ensure the manufacturer has done so and must keep a copy of the EU Declaration of Conformity available.

The retention period is ten years from the date the last unit of the product model is placed on the market. For some sector laws the period differs, so check each applicable act.

The file must be made available to market surveillance authorities on request, in a language they can understand. Authorities can request it during inspections or following an incident.

## Common technical file failures

* **No risk assessment.** The most frequent gap. Test reports alone do not constitute a file without the documented hazard analysis.
* **Standards listed but not applied.** Citing a harmonised standard without evidence it was actually followed.
* **Outdated after design changes.** The file reflects the original design but the product has since changed components or suppliers.
* **Missing importer verification.** The importer cannot produce the file because the manufacturer never provided access.
* **Wrong language.** The file exists but the authority cannot evaluate it.

