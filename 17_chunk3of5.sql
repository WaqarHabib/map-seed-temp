* The product identification: model, type, batch or serial number
* The manufacturer name and address
* A statement of sole responsibility for the declaration
* The object of the declaration with identification sufficient for traceability
* References to the applicable UK legislation, not the EU directives
* References to the UK designated standards applied
* Where applicable, the approved body details and certificate references
* The signatory: name, function, place and date of issue, and signature

The declaration must accompany the product or be available as required by the specific legislation. Like the EU declaration, it must be kept for ten years from the last product placed on the market.

The most common error is issuing a declaration that references EU directives rather than UK regulations. The legal basis must match the market.

## How do UKCA rules apply to Northern Ireland?

Northern Ireland occupies a special position. Under the Windsor Framework, EU product rules continue to apply in Northern Ireland, and the CE marking remains the relevant conformity marking for the Northern Ireland market.

Products placed on the Northern Ireland market need CE marking under EU rules. The UKNI marking applies in specific circumstances where a UK body was involved in the conformity assessment for the Northern Ireland market.

For sellers, the practical map is:

* **Great Britain:** UKCA marking under UK law
* **Northern Ireland:** CE marking under EU law
* **EU/EEA:** CE marking under EU law

