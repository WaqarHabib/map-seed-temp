* The module grant notes any limitations, such as approved antenna types or host configurations
* The host product must follow the module integration instructions; deviations void the reliance on the module grant
* The host may still require its own authorisation for unintentional radiator emissions from the digital circuitry
* Labelling must reflect the correct FCC IDs: the module ID and, where required, the host ID

Single-modular and split-modular approvals have different integration rules. Read the grant conditions before designing the host product around a module.

