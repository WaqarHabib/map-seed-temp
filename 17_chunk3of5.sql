'## Short answer

In the United States, radio frequency devices require FCC equipment authorisation before they may be marketed. This includes intentional radiators such as Wi-Fi, Bluetooth, and cellular devices, and unintentional radiators such as most digital electronics. The authorisation route, Supplier Declaration of Conformity (SDoC) or Certification, depends on the device type and FCC rule part.

## What is FCC equipment authorisation?

The Federal Communications Commission regulates radio frequency devices under the Communications Act. Equipment authorisation is the process by which the FCC verifies that a device complies with the technical requirements before it can be legally marketed in the US.

"Marketing" is broadly defined. It includes sale, lease, import, and shipment. A device cannot be imported for sale without the required authorisation.

## Which products are covered?

FCC rules distinguish intentional and unintentional radiators:

**Intentional radiators** are devices that deliberately generate radio frequency energy to communicate. Examples:

* Wi-Fi routers, access points, and client devices
* Bluetooth speakers, headphones, and peripherals
* Cellular phones, tablets, and IoT modules
* Zigbee, LoRa, and other wireless sensors
* Remote controls using radio frequencies

**Unintentional radiators** are digital devices that generate radio frequency energy as a byproduct of operation. Examples:

* Computers, monitors, and peripherals
* LED lighting with digital drivers
* Industrial controllers with microprocessors
* Most mains-powered devices containing digital circuitry

If the product contains a microprocessor operating above 9 kHz, it is likely an unintentional radiator within Part 15 scope.

## What are the authorisation routes?

| Route | Applies to | Process |
|---|---|---|
| Supplier Declaration of Conformity (SDoC) | Most unintentional radiators | Manufacturer tests to the standard and declares conformity; no FCC filing |
| Certification | Intentional radiators and specified devices | Testing by an accredited lab, application through a Telecommunications Certification Body (TCB), FCC ID granted |

Certification is the more rigorous route. The device receives an FCC ID that must appear on the product labelling. The ID is searchable in the FCC equipment database.

## What testing is required?

Testing must address the applicable technical requirements, typically:

* Radiated emissions within the permitted limits
* Conducted emissions on power lines
* Frequency stability and occupied bandwidth for transmitters
* Specific absorption rate (SAR) or RF exposure evaluation where applicable

Testing for Certification must be performed by an FCC-recognised accredited laboratory. For SDoC, the responsible party must use appropriate test methods, and market surveillance can verify compliance.

## What labelling is required?

Certified devices must display the FCC ID. Part 15 devices must carry the compliance statement that the device complies with Part 15 of the FCC rules and that operation is subject to conditions including that it must accept any interference received.

The FCC ID and statements must be on the product or, where the device is too small, in the user manual and on the packaging per the labelling rules.

## How does FCC relate to other US requirements?

FCC authorisation addresses electromagnetic compatibility and radio performance. It does not address electrical safety, which is typically demonstrated through listing by a Nationally Recognized Testing Laboratory (NRTL) such as UL or ETL, often required by retailers and electrical codes rather than federal law.

A wireless consumer product sold in the US commonly needs both FCC authorisation and safety listing, plus CPSC compliance for general product safety.

