UKCA marking is the conformity mark for products placed on the Great Britain market (England, Scotland, Wales) under UK product safety legislation. It mirrors CE marking technical requirements in most sectors but operates under separate UK statutory instruments, with distinct rules for importers, authorised representatives, and approved bodies.

## What is UKCA marking?

UKCA stands for UK Conformity Assessed. It is the marking used to demonstrate compliance with UK product safety law for manufactured goods placed on the market in Great Britain.

Before Brexit, CE marking demonstrated compliance with EU law applicable in the UK. After the transition period, the UK established its own product safety regime by retaining EU law as domestic law and then amending it. UKCA is the visible mark of that domestic regime.

Northern Ireland follows different arrangements under the Northern Ireland Protocol, where EU rules continue to apply for manufactured goods and CE marking remains relevant.

## How does UKCA differ from CE marking?

Technically, the underlying requirements are closely aligned because UK law was originally copied from EU directives. The differences are jurisdictional and procedural:

| Element | CE marking (EU/EEA) | UKCA marking (Great Britain) |
|---|---|---|
| Legal basis | EU directives and regulations | UK statutory instruments |
| Market | EEA | Great Britain |
| Conformity body | EU notified body | UK approved body |
| Authorised representative | Based in the EEA | Based in the UK |
| Importer definition | Imports into the EEA | Imports into the UK |
| Declaration | EU Declaration of Conformity | UK Declaration of Conformity |

A UK approved body is a conformity assessment body designated under UK law. An EU notified body cannot issue UKCA certificates, and a UK approved body cannot issue CE certificates for the EU market.

## When is UKCA marking required?

UKCA marking is required for product categories that previously required CE marking, when those products are placed on the Great Britain market. This includes electrical equipment, machinery, toys, personal protective equipment, and other manufactured goods covered by the relevant UK statutory instruments.

The government has published sector-by-sector guidance. The starting point is the GOV.UK guide "Placing manufactured goods on the market in Great Britain," which links to the specific rules for each product area.

## What is the current position on CE recognition?

The UK government has adjusted its policy on recognising CE marking several times since Brexit. Transitional arrangements have allowed CE-marked products to continue being placed on the Great Britain market in various sectors, with deadlines extended on multiple occasions.

Because the policy has moved, sellers must check the current position on gov.uk for their specific product sector before deciding on a marking strategy. Do not rely on older guidance.

## What must importers and distributors do?

A business that was a distributor for EU purposes may become an importer for UK purposes if it brings products into Great Britain from the EU or elsewhere. Importers have specific duties:

* Ensure the product complies with the applicable UK statutory instruments
* Verify the manufacturer has completed conformity assessment
* Add importer name and UK contact address to the product or packaging
* Keep the UK Declaration of Conformity and technical documentation available

Authorised representatives must be established in the UK. An EEA-based authorised representative does not satisfy the UK requirement.

