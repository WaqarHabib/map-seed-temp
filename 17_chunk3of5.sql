The UK regime, like the EU regime, distinguishes finished products from components. Partly completed machinery and components intended for incorporation have their own documentation duties rather than full UKCA marking.

Sellers of components should provide the information their customers need for the finished product assessment: materials declarations, test data, and any UKCA or CE documentation for the component as supplied. Clear commercial documentation reduces friction when the finished product manufacturer compiles its file.

## How to monitor for divergence between UK and EU rules?

UK law was copied from EU law but can now diverge. Divergence may be technical, through amended requirements, or procedural, through different implementation dates or guidance.

A monitoring process should:

* Track OPSS guidance updates alongside European Commission guidance for the same product area
* Note where UK statutory instruments have been amended since the retained EU version
* Assess each divergence for product impact: does it change the requirements, the assessment route, or only the paperwork
* Update the UK technical file sections affected, keeping EU sections unchanged unless EU law also moved

For most product areas divergence has been limited, but the direction is set by policy and sellers should not assume permanent alignment.

