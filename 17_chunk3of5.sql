* Start from the root cause: which design feature, component batch, or production process created the hazard
* Map the root cause to production records: date ranges, batch numbers, serial ranges, supplier lots
* Consider whether the same root cause affects other models or variants sharing the component or process
* Document the reasoning for including and excluding each product group

