Modern products often combine Wi-Fi, Bluetooth, cellular, and other radios. Each transmitter must comply with its applicable rule part, and the combination must be evaluated:

* Simultaneous transmission must be assessed for RF exposure where the device operates near the body
* The host must address intermodulation and spurious emissions from the combination
* Each certified module grant must be valid for the integrated configuration

The certification application should describe the complete radio configuration as marketed. Adding a radio after certification requires reassessment.

