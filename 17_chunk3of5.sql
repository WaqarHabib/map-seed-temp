The FCC coordinates with US Customs and Border Protection on import surveillance. Devices without required authorisation can be refused entry. The FCC also conducts market surveillance, including purchases of products offered online, and can impose forfeitures for violations.

For importers, the practical requirements:

* Ensure the FCC ID is properly labelled before shipment
* Keep the authorisation records available for customs queries
* Verify that the shipped configuration matches the authorised configuration; firmware or hardware changes after authorisation create risk
* For SDoC products, maintain the test records supporting the declaration

The FCC equipment database is public. Competitors, customers, and authorities can all verify whether a marketed device holds the claimed authorisation.

## How does the Supplier Declaration of Conformity process work?

The SDoC procedure allows the responsible party to test the product and declare conformity without FCC filing. The requirements:

* Testing must be performed for the applicable rule part, using recognised procedures
* The responsible party must be located in the US
* The declaration must identify the product and the standards applied
* Records supporting the declaration must be retained and produced on request
* The product must carry the required labelling and the SDoC compliance information

SDoC is not self-certification without evidence. The test records must exist and must support the declaration. An SDoC without underlying test data is a violation.

Importers using SDoC should obtain the test records from the manufacturer and confirm the US responsible party arrangement before importing. The importer may itself act as the responsible party if it takes on the obligations.

## What labelling does the FCC require?

FCC labelling requirements vary by authorisation type:

* **Certified devices** must display the FCC ID in the format specified in the rules. The ID links to the grant in the FCC database.
* **SDoC devices** must carry the compliance logo and information as specified for the rule part.
* **All devices** must carry any required warning statements for the rule part, such as the interference statement for Part 15 devices.

The label must be permanently affixed and legible. For small devices where the label cannot fit, the rules provide for display in the manual or on the packaging, but the conditions are specific and must be followed exactly.

Electronic labelling (display on a screen) is permitted for certain device categories under defined conditions. Confirm eligibility before relying on e-labelling.

## How should sellers verify supplier FCC claims?

Suppliers sometimes assert FCC compliance without proper authorisation. Verification steps:

1. **Check the FCC database.** Search the claimed FCC ID in the FCC equipment authorisation database. A valid grant should appear with the product details.
2. **Match the grant to the product.** Confirm the grant covers the product configuration being purchased, including model numbers and radio specifications.
3. **Review the grant conditions.** Note any limitations on antennas, host configurations, or operating conditions.
4. **Request the test reports.** For SDoC products, obtain the underlying test data.
5. **Confirm no modifications.** Verify that the product as supplied matches the authorised configuration.

A supplier unable or unwilling to provide the FCC ID or test records should be treated as a compliance risk. Build verification into the supplier qualification process rather than discovering issues at the border.

## What are the consequences of marketing without authorisation?

Marketing a device that requires FCC authorisation without obtaining it exposes the seller to enforcement action. The FCC has imposed forfeitures for marketing uncertified devices, with amounts reflecting the scale of the violation and the conduct involved.

Beyond FCC action, the commercial consequences include:

* Customs refusal of shipments identified as non-compliant
* Marketplace delisting where platforms enforce authorisation requirements
* Contractual liability to distributors and retailers who relied on the compliance representation
* Reputational damage with commercial customers who verify authorisation

The FCC equipment database makes verification straightforward for any interested party. Sellers should assume that significant commercial customers and competitors will check.

For startups and small importers, the authorisation cost can seem disproportionate to early revenues. But the cost of enforcement, including stopped shipments and legal fees, invariably exceeds the cost of doing the authorisation correctly from the start.

## How do you stay current with FCC rule changes?

FCC rules evolve through rulemakings that can change authorisation requirements, test procedures, and labelling. A monitoring approach:

* Track FCC rulemakings affecting the rule parts relevant to your products through the FCC Electronic Comment Filing System
* Review test laboratory guidance, as labs are often the first to flag practical changes in FCC expectations
* Reassess products when rule changes take effect, particularly where transition periods apply
* Update internal checklists and supplier requirements to reflect the new rules

For importers with stable product ranges, an annual review of the FCC rules against the product portfolio is sufficient. For sellers introducing new wireless products frequently, monitoring should be continuous.

