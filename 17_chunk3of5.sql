* Where self-assessment is permitted under the UK legislation, the manufacturer follows the same technical process as for the EU, but references UK designated standards and UK law in the file
* Where third-party assessment is required, a UK approved body must be used; an EU notified body assessment does not satisfy the UK requirement
* Test reports from competent laboratories can support both UK and EU assessments where the technical requirements are identical, but the assessment decision must be made under the correct regime

