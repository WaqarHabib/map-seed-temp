* The initial hazard report and the risk assessment
* The scope analysis with its supporting production records
* Authority notifications with dates and reference numbers
* Customer communications as issued, with distribution records
* Retailer and distributor briefings
* Return and remedy tracking data against the distribution baseline
* The root-cause analysis and the corrective actions implemented
* The closure report submitted to the authority

