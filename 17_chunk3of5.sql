## Why recalls are the costliest outcome

Regulatory penalties make headlines, but recalls drive the real expense. A recall combines every cost category at once: reverse logistics, customer communication, product rework or destruction, legal exposure, and brand damage. The operational disruption alone can exceed the original penalty many times over.

