Products already placed on the market before a regulatory change are generally governed by the rules in force at the time of placing. The key concept is the moment of first making available, not the moment of sale to the consumer.

For stock manufactured and placed on the market under previous arrangements, sellers should:

* Document the placing-on-the-market date with commercial records
* Confirm that the compliance basis at that date was valid
* For ongoing production, transition to the current requirements

Where the rules for existing stock are unclear for a specific product category, OPSS guidance is the reference point. Do not assume that old stock is automatically exempt from new requirements without checking the transitional provisions.

