## What triggers a recall decision?

A recall is warranted when a product on the market presents a risk that cannot be addressed while the product remains with consumers. The decision follows a risk assessment considering:

* The severity of the potential harm
* The probability of the hazardous scenario occurring
* The population exposed, with attention to vulnerable users
* Whether the risk can be mitigated without retrieving the product

Not every safety issue requires a full consumer recall. Some are addressed through warnings, repairs, or software updates. The assessment must be documented and defensible.

