## How do fulfilment models affect obligations?

The seller obligations apply regardless of fulfilment model, but the practical compliance steps differ:

**Self-fulfilment.** The seller controls the product, the packaging, and the shipping. Compliance verification happens at the seller premises before dispatch.

**Third-party logistics (3PL).** The 3PL handles storage and dispatch. The seller must ensure the 3PL ships the correct product configuration with the correct labelling, and that returns are handled in a way that preserves traceability.

**Dropshipping.** The supplier ships directly to the consumer. The seller has the least control and the highest risk. Verification must happen through supplier qualification, sample inspection, and contractual requirements, because the seller cannot inspect each unit.

**Marketplace fulfilment.** The marketplace warehouses and ships the product. The seller must provide compliant products and accurate product data to the marketplace, and understand the marketplace terms on compliance responsibility.

Each model requires the seller to map where compliance is verified and by whom. Gaps in the map are where failures occur.

## What triggers increased surveillance attention for online sellers?

Market surveillance authorities use risk-based targeting. Factors that increase the likelihood of scrutiny:

* Product categories with known safety issues or frequent Safety Gate alerts
* Sellers with prior non-compliance findings
* Listings with missing or suspicious traceability information
* Prices significantly below market norms, suggesting counterfeit or substandard products
* High-volume sellers in regulated categories
* Consumer complaints or injury reports linked to the seller products

Sellers cannot control all these factors, but they can control the compliance signals: complete traceability information, responsive communication with authorities, and documented product files. Sellers who present as organised and compliant receive less intensive attention than those who appear evasive or disorganised.

## How should sellers document their EU economic operator?

The EU economic operator is central to GPSR compliance for non-EU sellers. The documentation should establish:

* The identity of the operator: legal name, postal address, and electronic contact
* The basis of the appointment: authorised representative mandate, importer agreement, or fulfilment service provider arrangement
* The scope: which products the operator covers
* The operator acceptance: written confirmation that the operator has agreed to the role and understands the duties

This documentation should be available for each product. An authority checking a listing will look for the operator details; an authority conducting a deeper review will ask for the appointment basis.

Review the arrangement periodically. If the operator relationship ends, the seller must appoint a replacement before continuing to place products on the market. Products without an EU operator cannot lawfully remain on sale.

## What should a seller compliance checklist include?

A practical pre-listing checklist for EU online sales:

* Product safety file complete: risk assessment, test evidence, traceability labelling defined
* Manufacturer identification and contact details confirmed for the listing
* EU economic operator appointed and details verified for display
* Safety warnings and instructions prepared in the languages of each country served
* Listing information reviewed against the physical product for consistency
* Incident monitoring process assigned with a named responsible person
* Authority cooperation procedure documented with contact details

Run the checklist for each new product and review it annually for existing listings. The checklist is the operational translation of the legal duties.

## How do seller duties compare across fulfilment models?

| Duty | Self-fulfilment | 3PL | Dropshipping | Marketplace fulfilment |
|------|----------------|-----|--------------|----------------------|
| Product safety file | Seller prepares | Seller prepares | Seller prepares | Seller prepares |
| Physical label control | Direct | Via 3PL agreement | Via supplier contract | Via product data |
| Listing information | Seller publishes | Seller publishes | Seller publishes | Seller provides data |
| Incident monitoring | Seller | Seller | Seller | Shared with platform |
| Authority cooperation | Seller | Seller leads | Seller leads | Coordinated |

The safety file duty never transfers regardless of fulfilment model. What changes is how the seller exercises control over the physical product and the listing. Map each duty to a named responsible party for every fulfilment arrangement in use.

