## What happens during the assessment itself?

Understanding the assessment process helps manufacturers prepare and avoid delays:

**Documentation review.** The notified body examines the technical documentation for completeness and coherence before testing begins. Gaps identified here pause the process until resolved. A well-structured file shortens this phase significantly.

**Testing.** Depending on the module, the body tests samples itself, witnesses testing, or reviews test reports from recognised laboratories. The test plan follows the applicable harmonised standards and the essential requirements.

**Evaluation.** The body evaluates whether the evidence demonstrates conformity. Findings are communicated as non-conformities requiring correction, observations for improvement, or acceptance.

**Decision and certification.** On satisfactory evaluation, the body issues the relevant certificate or decision: EU type-examination certificate, quality system approval, or product verification as applicable.

**Surveillance.** Modules involving quality assurance include ongoing surveillance: periodic audits and sometimes unannounced visits. Budget for these as recurring costs.

## How do you manage the relationship over the product lifecycle?

The notified body relationship extends beyond the initial certificate:

* Inform the body of design changes that could affect conformity; the certificate may need amendment
* Prepare for surveillance audits with the same rigour as the initial assessment
* Track certificate validity and renewal dates; expired certificates cannot support ongoing production
* If switching bodies, plan the transfer: the new body must satisfy itself of conformity, which takes time

Treat the notified body as a long-term technical partner rather than a one-time vendor. Continuity of the assessment team improves efficiency across product generations.

## What are the alternatives to notified body involvement?

Where the directive permits self-assessment modules, manufacturers may avoid notified body involvement entirely. This is common for lower-risk products under Module A.

The trade-off is responsibility: self-assessment places the full burden of demonstrating conformity on the manufacturer, with no third-party validation. For complex products or novel technologies, voluntary engagement of a body, even where not required, can strengthen the file and commercial credibility.

Some manufacturers use a hybrid: self-assessment for the initial placing on the market, with a notified body engaged for specific aspects such as radio testing under the Radio Equipment Directive where the harmonised standards do not fully cover the requirements.

## How do fees and timelines compare?

Notified body engagement involves costs and scheduling that should be understood before commitment:

**Fee structures** vary by body and product complexity. Typical components include application fees, documentation review, testing charges, certification fees, and ongoing surveillance costs. Obtain a detailed quotation breaking down each element rather than a single figure.

**Timelines** depend on the body workload, the product complexity, and the quality of the submitted documentation. A complete, well-organised file moves faster. Bodies with sector specialisation in the product area are typically more efficient because their assessors know the standards and failure modes.

**Retesting risk.** If testing reveals non-conformities, the timeline extends by the redesign and retest cycle. Budget contingency for at least one round of findings on novel products.

When comparing bodies, evaluate the total cost of the relationship over the certificate lifecycle, including surveillance, rather than just the initial certification fee. A lower initial fee with expensive surveillance may cost more overall.

## What should the contract with the notified body cover?

The engagement terms should address:

* The scope of the assessment: which directives, which modules, which product models
* The deliverables: certificates, reports, and their format
* The timeline commitments and the assumptions behind them
* The fee structure and payment terms, including charges for additional work
* Confidentiality protections for the technical documentation
* The process for handling non-conformities and reassessment
* Suspension and withdrawal conditions for certificates
* The transfer provisions if the relationship ends

Review the body standard terms rather than assuming they match commercial norms. Notified bodies operate under accreditation constraints that affect their flexibility on some points.

## How do you handle disagreements with assessment findings?

Disagreements arise, particularly on novel products where the standards allow interpretation. The constructive approach:

* **Understand the finding.** Ask the assessor to explain the requirement and the evidence gap precisely. Many disagreements dissolve when the finding is clarified.
* **Provide additional evidence.** If the finding reflects missing evidence rather than actual non-conformity, supply it.
* **Present technical argument.** Where the interpretation is genuinely debatable, present a reasoned technical case with supporting references.
* **Use the body complaints process.** Accredited bodies have formal processes for disputing findings.
* **Seek a second view.** In persistent disagreements, another body assessment or independent expert opinion can clarify the position.

Maintain a professional relationship throughout. The assessor is applying the requirements as they understand them; adversarial approaches rarely improve outcomes.

## How does accreditation constrain what bodies can do?

Notified bodies operate under accreditation and notification that define their scope precisely. Understanding the constraints helps manufacturers set expectations:

* A body can only assess within its notified scope: the directives and product categories for which it is designated
* The body must maintain impartiality; it cannot consult on the design it will assess
* Assessment decisions must be made by competent personnel meeting the qualification requirements
* The body is subject to surveillance by its notifying authority and can have its notification restricted or withdrawn

If a body notification is withdrawn while assessments are in progress, the manufacturer must transfer to another body. Certificates issued by a body that later loses notification remain valid for products already placed on the market, but ongoing production needs a new assessment arrangement.

Check the NANDO database not just at selection but periodically during long product lifecycles.

