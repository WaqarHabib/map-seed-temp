A notified body is an independent organisation designated by an EU member state to carry out conformity assessment where the applicable EU directive requires third-party involvement. Select one by verifying its notification scope covers your directive and product category in the NANDO database, then evaluating technical competence, capacity, language, location, and commercial terms.

## What is a notified body?

Under the New Legislative Framework, certain conformity assessment modules require the involvement of a third party. That third party is a notified body: a conformity assessment body that a member state has notified to the European Commission as competent for specified legislation and product categories.

Notified bodies conduct activities such as type examination, production quality assurance assessment, and product verification, depending on the module. Their decisions, such as EU type-examination certificates, are recognised across the EEA.

The Commission maintains the NANDO database (New Approach Notified and Designated Organisations), the authoritative public list of notified bodies and their scopes.

## When is a notified body required?

Whether a notified body is needed depends on the applicable directive and the conformity assessment module the manufacturer selects. The pattern across directives:

| Situation | Notified body needed? |
|---|---|
| Module A (internal production control) | No, self-assessment |
| Module A1/A2 (internal control plus supervised testing) | Partial, supervised product checks |
| Module B (EU type-examination) plus C/D/E/F | Yes, type-examination by a notified body |
| Module D/E (production/product quality assurance) | Yes, quality system approval |
| Module G (unit verification) | Yes, per-unit verification |
| Module H (full quality assurance) | Yes, design and production QA approval |

Low-risk products under many directives can use Module A without any third-party involvement. Higher-risk categories, or modules the manufacturer selects for commercial reasons, require a notified body.

## How to verify a notified body scope

1. Open the NANDO database and search by directive and country, or by body name.
2. Open the body entry and read its notification scope: the directives and the product categories or conformity assessment procedures it is notified for.
3. Confirm the scope covers your specific directive and the module you intend to use.
4. Check the notification is current and not suspended or withdrawn.

A body notified for the EMC Directive cannot assess under the Machinery Regulation unless separately notified for it. Scope precision matters.

## How to evaluate candidates

Beyond scope, assess:

* **Technical competence.** Experience with your product technology and the applicable standards. Ask for relevant references.
* **Capacity and timing.** Certification lead times vary significantly. Confirm the body can meet your schedule.
* **Language.** The assessment will generate findings and certificates. Confirm working language compatibility.
* **Location and logistics.** Testing may require shipping products or hosting audits. Factor in geography.
* **Commercial terms.** Fee structures differ: fixed project fees, daily rates, annual surveillance charges. Obtain written quotations.
* **Accreditation.** Notification is the legal status; accreditation to ISO/IEC 17065 or 17025 supports confidence in technical quality.

## What does the engagement look like?

A typical type-examination engagement:

1. Application with product description and technical documentation
2. Documentation review by the notified body
3. Testing, either at the body laboratory or a recognised facility
4. Evaluation and decision
5. Issue of the EU type-examination certificate
6. Ongoing surveillance where the module requires it, such as periodic audits under Module D

The manufacturer retains full responsibility for conformity. The notified body certificate is evidence within the technical file, not a transfer of liability.

## Common selection mistakes

* **Choosing by price alone.** The cheapest body with the longest lead time can delay market entry by months.
* **Assuming scope.** A body well known in one directive may lack notification for yours.
* **Ignoring surveillance costs.** Modules with ongoing audits carry annual charges that should be budgeted from the start.
* **Late engagement.** Involving the body after design freeze risks costly redesign if findings emerge.

