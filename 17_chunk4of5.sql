E-commerce sellers offering products to EU consumers must display manufacturer and importer traceability details before the purchase is completed, ensure the products comply with applicable EU legislation, and cooperate with market surveillance authorities. Online marketplaces carry additional duties: Safety Gate registration, a single point of contact for authorities, and action on notices concerning dangerous products.

## Why online sellers face specific duties

The EU product safety framework was modernised precisely because e-commerce changed how products reach consumers. Direct imports, dropshipping, and marketplace listings created gaps where no economic operator in the EU could be held accountable.

The GPSR and the Market Surveillance Regulation close those gaps with duties that attach to the online offer itself, not just the physical product. If you offer a product to EU consumers online, the obligations apply regardless of where you are established.

## What information must the online listing show?

Under the GPSR, distance sellers must ensure that offers display, before the consumer is bound:

* The manufacturer name, registered trade name or trademark, and contact address including electronic address
* Where the manufacturer is outside the EU, the name and contact details of the EU economic operator (importer or authorised representative)
* Information identifying the product, such as a picture, the type, and batch or serial identifiers where applicable
* Safety warnings and instructions required for the product

A listing that omits the EU economic operator details is non-compliant on its face, before any product safety question arises.

